func TestReconcileReturnsStatusContextErrorsWithoutPersistingStatus(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)

	for _, test := range []struct {
		name          string
		cause         error
		cancelAtWrite bool
	}{
		{
			name:          "canceled",
			cause:         context.Canceled,
			cancelAtWrite: true,
		},
		{
			name:  "expired",
			cause: context.DeadlineExceeded,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			routing := serviceSyncContextRouting()
			routing.Spec.RoutingClass = ""
			originalStatus := routing.Status.DeepCopy()
			scheme := routingTestScheme(t)
			backing := fake.NewClientBuilder().WithScheme(scheme).WithStatusSubresource(routing).WithObjects(routing).Build()
			deadline := time.Now().Add(time.Minute)
			if test.cause == context.DeadlineExceeded {
				deadline = time.Now().Add(-time.Minute)
			}
			ctx, cancel := context.WithDeadline(context.WithValue(context.Background(), testContextKey{}, "routing-status-context"), deadline)
			defer cancel()

			var gotValue any
			var gotDeadline time.Time
			var hasDeadline bool
			statusUpdates := 0
			intercepted := interceptor.NewClient(backing, interceptor.Funcs{
				Get: func(_ context.Context, cl client.WithWatch, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
					// The expired input must still reach the status API boundary.
					return cl.Get(context.Background(), key, obj, opts...)
				},
				SubResourceUpdate: func(statusCtx context.Context, cl client.Client, subResource string, obj client.Object, opts ...client.SubResourceUpdateOption) error {
					statusUpdates++
					gotValue = statusCtx.Value(testContextKey{})
					gotDeadline, hasDeadline = statusCtx.Deadline()
					if test.cancelAtWrite {
						cancel()
					}
					if err := statusCtx.Err(); err != nil {
						return err
					}
					return cl.SubResource(subResource).Update(statusCtx, obj, opts...)
				},
			})
			r := DevWorkspaceRoutingReconciler{
				Client: intercepted, NonCachingClient: intercepted, Scheme: scheme,
				Log: logr.Discard(), SolverGetter: &solvers.SolverGetter{},
			}

			_, err := r.Reconcile(ctx, recoveryRequest(routing))
			if !errors.Is(err, test.cause) {
				t.Fatalf("want status write error %v, got %v", test.cause, err)
			}
			if gotValue != "routing-status-context" || !hasDeadline || !gotDeadline.Equal(deadline) {
				t.Fatalf("status update lost reconcile context: value=%v deadline=%v present=%v", gotValue, gotDeadline, hasDeadline)
			}
			if statusUpdates != 1 {
				t.Fatalf("want one status update, got %d", statusUpdates)
			}

			actual := &controllerv1alpha1.DevWorkspaceRouting{}
			if err := backing.Get(context.Background(), client.ObjectKeyFromObject(routing), actual); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(actual.Status, *originalStatus) {
				t.Fatalf("context error changed persisted status:\nwant: %#v\n got: %#v", *originalStatus, actual.Status)
			}
		})
	}
}
