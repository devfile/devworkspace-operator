func TestReconcileRetriesOrdinaryServiceSyncError(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	routing := serviceSyncContextRouting()
	backing := fake.NewClientBuilder().WithScheme(routingTestScheme(t)).WithStatusSubresource(routing).WithObjects(routing).Build()
	transientErr := errors.New("temporary Service API failure")
	tracker := &serviceSyncReconcileTracker{err: transientErr}
	cached := serviceSyncReconcileClient{Client: backing, tracker: tracker}
	fresh := serviceSyncReconcileClient{Client: backing, tracker: tracker, fresh: true}
	reconciler := DevWorkspaceRoutingReconciler{
		Client: cached, NonCachingClient: fresh, Scheme: routingTestScheme(t),
		Log: logr.Discard(), SolverGetter: &solvers.SolverGetter{},
	}

	result, err := reconciler.Reconcile(context.Background(), ctrl.Request{NamespacedName: client.ObjectKeyFromObject(routing)})
	if err != nil || !result.Requeue {
		t.Fatalf("ordinary Service sync error should request retry without returning an error, got result=%#v err=%v", result, err)
	}
	if !reflect.DeepEqual(tracker.operations, []string{"list", "get", "status"}) || tracker.statusCalls != 1 || tracker.statusUpdates != 1 {
		t.Fatalf("ordinary Service sync error did not finish status handling: %#v", tracker)
	}
	actual := &controllerv1alpha1.DevWorkspaceRouting{}
	if err := backing.Get(context.Background(), client.ObjectKeyFromObject(routing), actual); err != nil {
		t.Fatal(err)
	}
	wantStatus := routing.Status
	wantStatus.Phase = controllerv1alpha1.RoutingPreparing
	wantStatus.Message = "Preparing services"
	if !reflect.DeepEqual(actual.Status, wantStatus) {
		t.Fatalf("ordinary Service sync error did not preserve routing data while marking Preparing:\nwant: %#v\n got: %#v", wantStatus, actual.Status)
	}
	if tracker.serviceCreates != 0 || tracker.serviceUpdates != 0 || tracker.serviceDeletes != 0 {
		t.Fatalf("ordinary Service sync error changed Services: %#v", tracker)
	}
}

