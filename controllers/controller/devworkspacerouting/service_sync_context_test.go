func TestSyncServicesPassesContextAndStopsOnCancellation(t *testing.T) {
	for _, operation := range []struct {
		name  string
		calls []string
	}{
		{"list", []string{"list"}},
		{"delete", []string{"list", "delete"}},
		{"get", []string{"list", "get"}},
		{"create", []string{"list", "get", "create"}},
		{"update", []string{"list", "get", "update"}},
	} {
		for _, cause := range []error{context.Canceled, context.DeadlineExceeded} {
			t.Run(operation.name+"/"+cause.Error(), func(t *testing.T) {
				scheme := routingTestScheme(t)
				routing := &controllerv1alpha1.DevWorkspaceRouting{
					ObjectMeta: metav1.ObjectMeta{Name: "routing", Namespace: "ns", UID: "routing-uid"},
					Spec:       controllerv1alpha1.DevWorkspaceRoutingSpec{DevWorkspaceId: "workspace-id"},
				}
				desired := corev1.Service{
					ObjectMeta: metav1.ObjectMeta{
						Name: "first", Namespace: "ns",
						Labels:          map[string]string{constants.DevWorkspaceIDLabel: "workspace-id"},
						OwnerReferences: []metav1.OwnerReference{{Kind: "DevWorkspaceRouting", UID: routing.UID, Controller: ptr.To(true)}},
					},
					Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "desired"}},
				}
				later := desired.DeepCopy()
				later.Name = "later"
				var objects []client.Object
				if operation.name == "delete" || operation.name == "update" {
					existing := desired.DeepCopy()
					existing.UID = "service-uid"
					existing.ResourceVersion = "7"
					existing.Spec.Selector = map[string]string{"app": "old"}
					if operation.name == "delete" {
						existing.Name = "obsolete"
						secondObsolete := existing.DeepCopy()
						secondObsolete.Name = "obsolete-later"
						objects = append(objects, secondObsolete)
					}
					objects = append(objects, existing)
				}
				backing := fake.NewClientBuilder().WithScheme(scheme).WithObjects(objects...).Build()
				before := &corev1.ServiceList{}
				if err := backing.List(context.Background(), before); err != nil {
					t.Fatal(err)
				}
				deadline := time.Now().Add(time.Minute)
				ctx, cancel := context.WithDeadline(context.WithValue(context.Background(), testContextKey{}, "sync-context"), deadline)
				defer cancel()
				apiErr := fmt.Errorf("Service %s: %w", operation.name, cause)
				var calls []string
				check := func(received context.Context, name string) error {
					calls = append(calls, name)
					gotDeadline, hasDeadline := received.Deadline()
					if received.Value(testContextKey{}) != "sync-context" || !hasDeadline || !gotDeadline.Equal(deadline) {
						t.Errorf("%s lost context value/deadline: value=%v deadline=%v present=%v", name, received.Value(testContextKey{}), gotDeadline, hasDeadline)
					}
					if name == operation.name {
						cancel()
						return apiErr
					}
					return nil
				}
				cached := interceptor.NewClient(backing, interceptor.Funcs{
					List: func(ctx context.Context, cl client.WithWatch, list client.ObjectList, opts ...client.ListOption) error {
						if err := check(ctx, "list"); err != nil {
							return err
						}
						return cl.List(ctx, list, opts...)
					},
					Get: func(context.Context, client.WithWatch, client.ObjectKey, client.Object, ...client.GetOption) error {
						t.Fatal("guarded Service GET used cached client")
						return nil
					},
					Delete: func(ctx context.Context, cl client.WithWatch, obj client.Object, opts ...client.DeleteOption) error {
						options := (&client.DeleteOptions{}).ApplyOptions(opts)
						if options.Preconditions == nil || options.Preconditions.UID == nil || *options.Preconditions.UID != obj.GetUID() || options.Preconditions.ResourceVersion == nil || *options.Preconditions.ResourceVersion != obj.GetResourceVersion() {
							t.Error("cleanup Delete lost UID/resource-version preconditions")
						}
						if err := check(ctx, "delete"); err != nil {
							return err
						}
						return cl.Delete(ctx, obj, opts...)
					},
					Create: func(ctx context.Context, cl client.WithWatch, obj client.Object, opts ...client.CreateOption) error {
						if err := check(ctx, "create"); err != nil {
							return err
						}
						return cl.Create(ctx, obj, opts...)
					},
					Update: func(ctx context.Context, cl client.WithWatch, obj client.Object, opts ...client.UpdateOption) error {
						if err := check(ctx, "update"); err != nil {
							return err
						}
						return cl.Update(ctx, obj, opts...)
					},
				})
				fresh := interceptor.NewClient(backing, interceptor.Funcs{
					Get: func(ctx context.Context, cl client.WithWatch, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
						if err := check(ctx, "get"); err != nil {
							return err
						}
						return cl.Get(ctx, key, obj, opts...)
					},
				})
				r := DevWorkspaceRoutingReconciler{Client: cached, NonCachingClient: fresh, Scheme: scheme, Log: logr.Discard()}
				ready, services, err := r.syncServices(ctx, routing, []corev1.Service{desired, *later})
				if ready || services != nil || err != apiErr || !errors.Is(err, cause) {
					t.Fatalf("want original cancellation and no Services, got ready=%v services=%v err=%v", ready, services, err)
				}
				if !errors.Is(ctx.Err(), context.Canceled) {
					t.Fatal("Service operation did not cancel the caller context")
				}
				if !reflect.DeepEqual(calls, operation.calls) {
					t.Errorf("operations continued after cancellation: want %v, got %v", operation.calls, calls)
				}
				after := &corev1.ServiceList{}
				if err := backing.List(context.Background(), after); err != nil {
					t.Fatal(err)
				}
				if !reflect.DeepEqual(before.Items, after.Items) {
					t.Errorf("canceled sync changed persisted Services: before=%#v after=%#v", before.Items, after.Items)
				}
			})
		}
	}
}
