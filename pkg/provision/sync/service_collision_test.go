func TestGenericServiceCollisionOutcomes(t *testing.T) {
	readFailure := errors.New("fresh read failed")
	for _, scenario := range []string{"already synchronized", "disappeared", "read error", "canceled", "update conflict", "no fresh client"} {
		t.Run(scenario, func(t *testing.T) {
			desired, existing := collisionServices()
			if scenario == "already synchronized" {
				// The Service became cache-visible after the cached miss.
				existing.Labels = desired.Labels
			}
			backing := fake.NewClientBuilder().WithObjects(existing).Build()
			ctx, cancel := context.WithCancel(context.Background())
			defer cancel()
			stale := interceptor.NewClient(backing, interceptor.Funcs{
				Get: func(_ context.Context, _ client.WithWatch, key client.ObjectKey, _ client.Object, _ ...client.GetOption) error {
					return apierrors.NewNotFound(schema.GroupResource{Resource: "services"}, key.Name)
				},
				Create: func(ctx context.Context, cl client.WithWatch, obj client.Object, opts ...client.CreateOption) error {
					err := cl.Create(ctx, obj, opts...)
					if scenario == "canceled" {
						cancel()
					}
					return err
				},
				Update: func(ctx context.Context, cl client.WithWatch, obj client.Object, opts ...client.UpdateOption) error {
					if scenario == "update conflict" {
						return apierrors.NewConflict(schema.GroupResource{Resource: "services"}, obj.GetName(), errors.New("changed"))
					}
					return cl.Update(ctx, obj, opts...)
				},
			})
			reader := interceptor.NewClient(backing, interceptor.Funcs{Get: func(ctx context.Context, cl client.WithWatch, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
				switch scenario {
				case "disappeared":
					return apierrors.NewNotFound(schema.GroupResource{Resource: "services"}, key.Name)
				case "read error":
					return readFailure
				case "canceled":
					return ctx.Err()
				default:
					return cl.Get(ctx, key, obj, opts...)
				}
			}})
			cached := &countingServiceClient{Client: stale}
			fresh := &countingServiceClient{Client: reader}
			api := ClusterAPI{Client: cached, NonCachingClient: fresh, Ctx: ctx, Logger: logr.Discard()}
			if scenario == "no fresh client" {
				api.NonCachingClient = nil
			}
			obj, err := SyncObjectWithCluster(desired, api)
			switch scenario {
			case "already synchronized":
				if err != nil || obj == nil || !reflect.DeepEqual(obj, existing) {
					t.Fatalf("want nonnil fresh Service, got obj=%v err=%v", obj, err)
				}
			case "read error":
				if !errors.Is(err, readFailure) {
					t.Fatalf("want fresh read error, got %v", err)
				}
			case "canceled":
				if !errors.Is(err, context.Canceled) {
					t.Fatalf("want cancellation, got %v", err)
				}
			default:
				var pending *NotInSyncError
				if !errors.As(err, &pending) || pending.Reason != NeedRetryReason {
					t.Fatalf("want retry, got %v", err)
				}
			}
			wantReads, wantUpdates := 1, 0
			if scenario == "no fresh client" {
				wantReads = 0
			}
			if scenario == "update conflict" {
				wantUpdates = 1
			}
			if cached.creates != 1 || fresh.gets != wantReads || cached.updates != wantUpdates || cached.deletes != 0 || fresh.creates != 0 || fresh.updates != 0 || fresh.deletes != 0 {
				t.Fatalf("unexpected collision calls: cached=%+v fresh=%+v", cached, fresh)
			}
			actual := &corev1.Service{}
			if err := backing.Get(context.Background(), client.ObjectKeyFromObject(existing), actual); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(actual, existing) {
				t.Fatalf("Service changed: %#v", actual)
			}
		})
	}
}

