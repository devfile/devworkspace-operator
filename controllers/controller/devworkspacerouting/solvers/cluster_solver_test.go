func TestClusterSolverGetSpecObjectsLongServingCertVolumeNames(t *testing.T) {
	longEndpointName := strings.Repeat("a", 39)
	derivedShortEndpointName := "b4d5e56e929ba4cda349"
	endpointNames := []string{
		strings.Repeat("a", 37),
		strings.Repeat("b", 38),
		longEndpointName,
		strings.Repeat("d", 63),
		strings.Repeat("x", 62) + "a",
		strings.Repeat("x", 62) + "b",
		derivedShortEndpointName,
	}
	endpoints := make(controllerv1alpha1.EndpointList, len(endpointNames))
	expectedMounts := map[string]string{
		"/var/serving-cert/": common.ServiceName("workspace-id"),
	}
	for i, name := range endpointNames {
		endpoints[i] = controllerv1alpha1.Endpoint{
			Name:       name,
			TargetPort: 7000 + i,
			Exposure:   controllerv1alpha1.InternalEndpointExposure,
			Attributes: controllerv1alpha1.Attributes{}.
				PutBoolean(string(controllerv1alpha1.DiscoverableAttribute), true),
		}
		expectedMounts["/var/serving-cert/"+name+"/"] = name
	}

	workspaceMeta := DevWorkspaceMetadata{
		DevWorkspaceId:   "workspace-id",
		DevWorkspaceName: "workspace",
		Namespace:        "workspace-namespace",
		PodSelector:      map[string]string{"workspace": "workspace-id"},
	}
	scheme := runtime.NewScheme()
	assert.NoError(t, corev1.AddToScheme(scheme))
	solver := NewClusterSolver(fake.NewClientBuilder().WithScheme(scheme).Build(), true)
	routing := &controllerv1alpha1.DevWorkspaceRouting{
		Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{
			Endpoints:   map[string]controllerv1alpha1.EndpointList{"main": endpoints},
			PodSelector: workspaceMeta.PodSelector,
		},
	}

	objects, err := solver.GetSpecObjects(routing, workspaceMeta)
	if !assert.NoError(t, err) {
		return
	}

	assert.Len(t, objects.Services, len(endpointNames)+1)
	assert.Len(t, objects.PodAdditions.Volumes, len(endpointNames)+1)
	assert.Len(t, objects.PodAdditions.VolumeMounts, len(endpointNames)+1)

	volumeSecrets := make(map[string]string, len(objects.PodAdditions.Volumes))
	volumeNamesBySecret := make(map[string]string, len(objects.PodAdditions.Volumes))
	for _, volume := range objects.PodAdditions.Volumes {
		if !assert.NotContains(t, volumeSecrets, volume.Name) {
			continue
		}
		assert.LessOrEqual(t, len(volume.Name), 63)
		if !assert.NotNil(t, volume.Secret) {
			continue
		}
		volumeSecrets[volume.Name] = volume.Secret.SecretName
		volumeNamesBySecret[volume.Secret.SecretName] = volume.Name
	}
	assert.Equal(t, "devworkspace-serving-cert-"+endpointNames[0], volumeNamesBySecret[endpointNames[0]])
	assert.Equal(t, "devworkspace-cert-b4d5e56e929ba4cda349", volumeNamesBySecret[longEndpointName])
	assert.Equal(t, "devworkspace-serving-cert-"+derivedShortEndpointName, volumeNamesBySecret[derivedShortEndpointName])

	actualMounts := make(map[string]string, len(objects.PodAdditions.VolumeMounts))
	for _, mount := range objects.PodAdditions.VolumeMounts {
		if !assert.NotContains(t, actualMounts, mount.MountPath) {
			continue
		}
		secretName, exists := volumeSecrets[mount.Name]
		if !assert.True(t, exists, "mount %q references volume %q", mount.MountPath, mount.Name) {
			continue
		}
		actualMounts[mount.MountPath] = secretName
	}
	assert.Equal(t, expectedMounts, actualMounts)
}
