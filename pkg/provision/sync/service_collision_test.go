func TestGenericNonServiceCollisionKeepsUpdateFallback(t *testing.T) {
	existing := &corev1.ConfigMap{ObjectMeta: metav1.ObjectMeta{Name: "config", Namespace: "ns"}, Data: map[string]string{"key": "old"}}
	desired := existing.DeepCopy()
	desired.Data["key"] = "new"
	backing := fake.NewClientBuilder().WithObjects(existing).Build()
	stale := interceptor.NewClient(backing, interceptor.Funcs{Get: func(_ context.Context, _ client.WithWatch, key client.ObjectKey, _ client.Object, _ ...client.GetOption) error {
		return apierrors.NewNotFound(schema.GroupResource{Resource: "configmaps"}, key.Name)
	}})
	fresh := &countingServiceClient{Client: backing}
	_, err := SyncObjectWithCluster(desired, ClusterAPI{Client: stale, NonCachingClient: fresh, Ctx: context.Background(), Logger: logr.Discard()})
	var pending *NotInSyncError
	if !errors.As(err, &pending) || pending.Reason != UpdatedObjectReason {
		t.Fatalf("want existing non-Service update behavior, got %v", err)
	}
	actual := &corev1.ConfigMap{}
	if err := backing.Get(context.Background(), client.ObjectKeyFromObject(existing), actual); err != nil {
		t.Fatal(err)
	}
	if actual.Data["key"] != "new" || fresh.gets != 0 {
		t.Fatalf("non-Service collision changed behavior: actual=%v freshGets=%d", actual, fresh.gets)
	}
}
