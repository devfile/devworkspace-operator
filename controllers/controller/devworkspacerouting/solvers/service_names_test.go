func TestClusterSolverRejectsDiscoverableEndpointUsingWorkspaceServiceName(t *testing.T) {
	for _, tt := range []struct {
		name string
		tls  bool
	}{
		{name: "plaintext", tls: false},
		{name: "TLS", tls: true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			scheme := runtime.NewScheme()
			assert.NoError(t, corev1.AddToScheme(scheme))
			solver := NewClusterSolver(fake.NewClientBuilder().WithScheme(scheme).Build(), tt.tls)
			const reservedServiceName = "mine-service"
			routing := &controllerv1alpha1.DevWorkspaceRouting{
				Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{
					Endpoints: map[string]controllerv1alpha1.EndpointList{
						"machine": {{
							Name:       reservedServiceName,
							TargetPort: 8080,
							Exposure:   controllerv1alpha1.InternalEndpointExposure,
							Attributes: controllerv1alpha1.Attributes{}.
								PutBoolean(string(controllerv1alpha1.DiscoverableAttribute), true),
						}},
					},
				},
			}
			objects, err := solver.GetSpecObjects(context.Background(), routing, DevWorkspaceMetadata{
				DevWorkspaceId: "mine",
				Namespace:      "test-namespace",
			})

			var invalid *RoutingInvalid
			assert.ErrorAs(t, err, &invalid)
			if assert.NotNil(t, invalid) {
				assert.Contains(t, invalid.Reason, "discoverable endpoint")
				assert.Contains(t, invalid.Reason, reservedServiceName)
			}
			assert.Empty(t, objects.Services)
		})
	}
}
