func TestReconcileTLSCertificatesTransitionPendingReadyAndFailed(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.OpenShiftv4)
	for _, routingClass := range []controllerv1alpha1.DevWorkspaceRoutingClass{
		controllerv1alpha1.DevWorkspaceRoutingClusterTLS,
		controllerv1alpha1.DevWorkspaceRoutingWebTerminal,
	} {
		t.Run(string(routingClass), func(t *testing.T) {
			r, backing, routing := newTLSReconciler(t, routingClass)
			request := ctrl.Request{NamespacedName: client.ObjectKeyFromObject(routing)}
			if _, err := r.Reconcile(context.Background(), request); err != nil {
				t.Fatal(err)
			}
			services := setTLSServiceUIDs(t, backing, routing)
			if len(services) < 2 {
				t.Fatalf("expected aggregate and discoverable TLS Services, got %d", len(services))
			}
			for _, service := range services[:len(services)-1] {
				if err := backing.Create(context.Background(), servingCertSecret(service)); err != nil {
					t.Fatal(err)
				}
			}
			result, err := r.Reconcile(context.Background(), request)
			if err != nil {
				t.Fatal(err)
			}
			if result.RequeueAfter != time.Second {
				t.Fatalf("pending serving certificate should requeue after one second, got %s", result.RequeueAfter)
			}
			stored := getRouting(t, backing, routing)
			if stored.Status.Phase != controllerv1alpha1.RoutingPreparing || stored.Status.PodAdditions != nil || stored.Status.ExposedEndpoints != nil {
				t.Fatalf("missing one serving cert must keep routing pending and clear additions/endpoints: %#v", stored.Status)
			}

			if err := backing.Create(context.Background(), servingCertSecret(services[len(services)-1])); err != nil {
				t.Fatal(err)
			}
			if _, err := r.Reconcile(context.Background(), request); err != nil {
				t.Fatal(err)
			}
			stored = getRouting(t, backing, routing)
			if stored.Status.Phase != controllerv1alpha1.RoutingReady || stored.Status.PodAdditions == nil || len(stored.Status.PodAdditions.Volumes) != len(services) {
				t.Fatalf("all serving certs should expose readiness and aggregate TLS additions: %#v", stored.Status)
			}

			if err := backing.Delete(context.Background(), servingCertSecret(services[0])); err != nil {
				t.Fatal(err)
			}
			if _, err := r.Reconcile(context.Background(), request); err != nil {
				t.Fatal(err)
			}
			stored = getRouting(t, backing, routing)
			if stored.Status.Phase != controllerv1alpha1.RoutingPreparing || stored.Status.PodAdditions != nil || stored.Status.ExposedEndpoints != nil {
				t.Fatalf("lost serving cert must clear previously published additions/endpoints: %#v", stored.Status)
			}

			if err := backing.Create(context.Background(), servingCertSecret(services[0])); err != nil {
				t.Fatal(err)
			}
			if _, err := r.Reconcile(context.Background(), request); err != nil {
				t.Fatal(err)
			}
			stored = getRouting(t, backing, routing)
			if stored.Status.Phase != controllerv1alpha1.RoutingReady || stored.Status.PodAdditions == nil || stored.Status.ExposedEndpoints == nil {
				t.Fatalf("restored serving cert should republish readiness: %#v", stored.Status)
			}

			invalidSecret := servingCertSecret(services[0])
			invalidSecret.Type = corev1.SecretTypeOpaque
			if err := backing.Update(context.Background(), invalidSecret); err != nil {
				t.Fatal(err)
			}
			if _, err := r.Reconcile(context.Background(), request); err != nil {
				t.Fatal(err)
			}
			stored = getRouting(t, backing, routing)
			if stored.Status.Phase != controllerv1alpha1.RoutingFailed || stored.Status.PodAdditions != nil || stored.Status.ExposedEndpoints != nil {
				t.Fatalf("invalid serving cert must fail and clear published additions/endpoints: %#v", stored.Status)
			}
		})
	}
}

