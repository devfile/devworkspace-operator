func TestRoutingPhasesStampObservedGeneration(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	t.Run("Preparing and Ready", func(t *testing.T) {
		routing := recoveryRouting(4)
		r, backing := recoveryReconciler(t, routing)
		request := recoveryRequest(routing)
		if _, err := r.Reconcile(context.Background(), request); err != nil {
			t.Fatal(err)
		}
		preparing := getRouting(t, backing, routing)
		if preparing.Status.Phase != controllerv1alpha1.RoutingPreparing || preparing.Status.ObservedGeneration != 4 {
			t.Fatalf("Preparing did not stamp generation: %#v", preparing.Status)
		}
		for range 3 {
			if _, err := r.Reconcile(context.Background(), request); err != nil {
				t.Fatal(err)
			}
		}
		ready := getRouting(t, backing, routing)
		if ready.Status.Phase != controllerv1alpha1.RoutingReady || ready.Status.ObservedGeneration != 4 {
			t.Fatalf("Ready did not stamp generation: %#v", ready.Status)
		}
	})
	t.Run("Failed", func(t *testing.T) {
		routing := recoveryRouting(7)
		routing.Spec.RoutingClass = ""
		r, backing := recoveryReconciler(t, routing)
		if _, err := r.Reconcile(context.Background(), recoveryRequest(routing)); err != nil {
			t.Fatal(err)
		}
		failed := getRouting(t, backing, routing)
		if failed.Status.Phase != controllerv1alpha1.RoutingFailed || failed.Status.ObservedGeneration != 7 {
			t.Fatalf("Failed did not stamp generation: %#v", failed.Status)
		}
	})
	t.Run("Stopped", func(t *testing.T) {
		routing := recoveryRouting(8)
		routing.Annotations = map[string]string{constants.DevWorkspaceStartedStatusAnnotation: "false"}
		routing.Status = controllerv1alpha1.DevWorkspaceRoutingStatus{Phase: controllerv1alpha1.RoutingReady}
		r, backing := recoveryReconciler(t, routing)
		if _, err := r.Reconcile(context.Background(), recoveryRequest(routing)); err != nil {
			t.Fatal(err)
		}
		stopped := getRouting(t, backing, routing)
		if stopped.Status.Phase != controllerv1alpha1.RoutingStopped || stopped.Status.ObservedGeneration != 8 {
			t.Fatalf("Stopped did not stamp generation: %#v", stopped.Status)
		}
	})
}

