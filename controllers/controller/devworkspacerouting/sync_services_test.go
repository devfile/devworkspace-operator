func TestReconcileMarksSynchronizationConflictFailed(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	scheme := runtime.NewScheme()
	if err := corev1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	if err := controllerv1alpha1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	routing := &controllerv1alpha1.DevWorkspaceRouting{ObjectMeta: metav1.ObjectMeta{Name: "routing-mine", Namespace: "ns", UID: "mine-routing"}, Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{DevWorkspaceId: "mine", RoutingClass: controllerv1alpha1.DevWorkspaceRoutingCluster, Endpoints: map[string]controllerv1alpha1.EndpointList{"main": {{Name: "api", TargetPort: 8080, Exposure: controllerv1alpha1.InternalEndpointExposure, Attributes: controllerv1alpha1.Attributes{}.PutBoolean("discoverable", true)}}}}}
	foreign := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns", UID: "foreign-service"}, Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "foreign"}}}
	backing := fake.NewClientBuilder().WithScheme(scheme).WithStatusSubresource(routing).WithObjects(routing, foreign).Build()
	r := DevWorkspaceRoutingReconciler{Client: serviceLabelFilteredClient{backing}, NonCachingClient: backing, Scheme: scheme, Log: logr.Discard(), SolverGetter: &solvers.SolverGetter{}}
	_, err := r.Reconcile(context.Background(), ctrl.Request{NamespacedName: client.ObjectKeyFromObject(routing)})
	if err != nil {
		t.Fatal(err)
	}
	actualRouting := &controllerv1alpha1.DevWorkspaceRouting{}
	if err := backing.Get(context.Background(), client.ObjectKeyFromObject(routing), actualRouting); err != nil {
		t.Fatal(err)
	}
	if actualRouting.Status.Phase != controllerv1alpha1.RoutingFailed {
		t.Fatalf("want permanent conflict, got %s: %s", actualRouting.Status.Phase, actualRouting.Status.Message)
	}
	actual := &corev1.Service{}
	if err := backing.Get(context.Background(), client.ObjectKeyFromObject(foreign), actual); err != nil {
		t.Fatalf("foreign Service deleted: %v", err)
	}
	if actual.Spec.Selector["app"] != "foreign" {
		t.Fatal("foreign Service modified")
	}
}

