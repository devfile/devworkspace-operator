func TestReconcileRetriesFailedRoutingAfterSpecChange(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	routing := recoveryRouting(1)
	foreign := &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns", UID: "foreign-service"},
		Spec:       corev1.ServiceSpec{Selector: map[string]string{"app": "foreign"}},
	}
	r, backing := recoveryReconciler(t, routing, foreign)
	r.Client = serviceLabelFilteredClient{backing}
	request := recoveryRequest(routing)
	if _, err := r.Reconcile(context.Background(), request); err != nil {
		t.Fatal(err)
	}
	failed := getRouting(t, backing, routing)
	if failed.Status.Phase != controllerv1alpha1.RoutingFailed || failed.Status.ObservedGeneration != 1 {
		t.Fatalf("want foreign Service conflict to fail generation 1, got %#v", failed.Status)
	}
	failed.Spec.Endpoints["main"][0].Name = "renamed"
	failed.Generation++
	if err := backing.Update(context.Background(), failed); err != nil {
		t.Fatal(err)
	}

	for range 3 {
		if _, err := r.Reconcile(context.Background(), request); err != nil {
			t.Fatal(err)
		}
	}
	actual := getRouting(t, backing, routing)
	if actual.Status.Phase != controllerv1alpha1.RoutingReady || actual.Status.ObservedGeneration != 2 {
		t.Fatalf("want spec change to retry routing to Ready, got %s: %s", actual.Status.Phase, actual.Status.Message)
	}
	if actual.UID != routing.UID {
		t.Fatalf("routing UID changed during recovery: want %s, got %s", routing.UID, actual.UID)
	}
	actualForeign := &corev1.Service{}
	if err := backing.Get(context.Background(), client.ObjectKeyFromObject(foreign), actualForeign); err != nil {
		t.Fatalf("foreign Service was deleted: %v", err)
	}
	if !reflect.DeepEqual(foreign, actualForeign) {
		t.Fatalf("foreign Service changed during recovery: %#v", actualForeign)
	}
}

