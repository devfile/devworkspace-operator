func assertServiceSyncContextUnchanged(t *testing.T, backing client.Client, routing *controllerv1alpha1.DevWorkspaceRouting) {
	t.Helper()
	actual := &controllerv1alpha1.DevWorkspaceRouting{}
	if err := backing.Get(context.Background(), client.ObjectKeyFromObject(routing), actual); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(actual.Status, routing.Status) {
		t.Fatalf("context error changed persisted routing status:\nwant: %#v\n got: %#v", routing.Status, actual.Status)
	}
	services := &corev1.ServiceList{}
	if err := backing.List(context.Background(), services); err != nil {
		t.Fatal(err)
	}
	if len(services.Items) != 0 {
		t.Fatalf("context error created Services: %#v", services.Items)
	}
}

