package sync

import (
	"fmt"

	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/controller-runtime/pkg/client"

	"github.com/devfile/devworkspace-operator/pkg/constants"
)

// SyncRoutingServiceWithCluster synchronizes a routing Service after a fresh ownership check.
// It falls back to the cached client when no non-caching client is configured.
func SyncRoutingServiceWithCluster(service *corev1.Service, api ClusterAPI) (client.Object, error) {
	reader := api.Client
	// Routing Services can be hidden by the cache when their workspace label is missing.
	if api.NonCachingClient != nil {
		reader = api.NonCachingClient
	}
	existing := &corev1.Service{}
	err := reader.Get(api.Ctx, client.ObjectKeyFromObject(service), existing)
	if err == nil {
		owner := metav1.GetControllerOf(service)
		existingOwner := metav1.GetControllerOf(existing)
		if owner != nil && (existingOwner == nil || owner.UID != existingOwner.UID) ||
			owner == nil && (service.Labels[constants.DevWorkspaceIDLabel] == "" || existing.Labels[constants.DevWorkspaceIDLabel] != service.Labels[constants.DevWorkspaceIDLabel]) {
			return nil, &UnrecoverableSyncError{&ServiceConflictError{EndpointName: service.Name, WorkspaceName: existing.Labels[constants.DevWorkspaceNameLabel]}}
		}
	}
	return syncObjectAfterRead(service, existing, err, api)
}

// ServiceConflictError reports a discoverable Service owned by another workspace.
// Generated by Codex
type ServiceConflictError struct {
	EndpointName  string
	WorkspaceName string
}

// Generated by Codex
func (e *ServiceConflictError) Error() string {
	if e.WorkspaceName == "" {
		return fmt.Sprintf("discoverable endpoint '%s' is already in use by another workspace", e.EndpointName)
	}
	return fmt.Sprintf("discoverable endpoint '%s' is already in use by workspace '%s'", e.EndpointName, e.WorkspaceName)
}
