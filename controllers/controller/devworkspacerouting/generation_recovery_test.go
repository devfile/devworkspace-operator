func TestChangedInvalidSpecFailsAndThenBecomesTerminal(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	routing := recoveryRouting(2)
	routing.Status = controllerv1alpha1.DevWorkspaceRoutingStatus{
		Phase: controllerv1alpha1.RoutingFailed, Message: "old generation failed", ObservedGeneration: 1,
		PodAdditions:     &controllerv1alpha1.PodAdditions{Volumes: []corev1.Volume{{Name: "stale"}}},
		ExposedEndpoints: map[string]controllerv1alpha1.ExposedEndpointList{"old": {{Name: "old", Url: "https://old"}}},
	}
	routing.Spec.Endpoints["other"] = recoveryEndpoints("api")
	client, backing := recoveryRecordingReconciler(t, routing)
	request := recoveryRequest(routing)
	if _, err := client.reconciler.Reconcile(context.Background(), request); err != nil {
		t.Fatal(err)
	}
	if len(client.statusHistory) < 2 || client.statusHistory[0].phase != controllerv1alpha1.RoutingPreparing ||
		client.statusHistory[0].message != "Retrying routing after spec change" || client.statusHistory[0].generation != 2 {
		t.Fatalf("new generation must persist Preparing before validating/provisioning: %#v", client.statusHistory)
	}
	failed := getRouting(t, backing, routing)
	if failed.Status.Phase != controllerv1alpha1.RoutingFailed || failed.Status.ObservedGeneration != 2 || failed.Status.Message == "" {
		t.Fatalf("invalid new generation should fail and stamp generation 2: %#v", failed.Status)
	}
	if failed.Status.PodAdditions != nil || failed.Status.ExposedEndpoints != nil {
		t.Fatalf("invalid new generation published stale routing results: %#v", failed.Status)
	}
	if len(client.statusHistory) != 2 || client.statusHistory[1].phase != controllerv1alpha1.RoutingFailed || client.statusHistory[1].generation != 2 {
		t.Fatalf("invalid new generation should write only Preparing then Failed: %#v", client.statusHistory)
	}
	writes := client.statusUpdates
	if _, err := client.reconciler.Reconcile(context.Background(), request); err != nil {
		t.Fatal(err)
	}
	if client.statusUpdates != writes {
		t.Fatalf("same-generation invalid routing wrote status again: before=%d after=%d", writes, client.statusUpdates)
	}
}

