func collisionServices() (desired, existing *corev1.Service) {
	desired = &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{
			Name: "api", Namespace: "ns",
			Labels:          map[string]string{constants.DevWorkspaceIDLabel: "mine"},
			OwnerReferences: []metav1.OwnerReference{{APIVersion: "workspace.devfile.io/v1alpha2", Kind: "DevWorkspace", Name: "workspace", UID: "workspace-uid"}},
		},
		Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "mine"}, Ports: []corev1.ServicePort{{Port: 8080}}},
	}
	existing = desired.DeepCopy()
	existing.Labels = nil
	existing.UID = "existing-service"
	existing.ResourceVersion = "7"
	existing.Spec.ClusterIP = "10.0.0.1"
	return desired, existing
}

