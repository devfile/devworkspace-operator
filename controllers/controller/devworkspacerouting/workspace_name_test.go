func TestReconcileUsesDevWorkspaceOwnerName(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	g := NewWithT(t)
	scheme := runtime.NewScheme()
	g.Expect(corev1.AddToScheme(scheme)).To(Succeed())
	g.Expect(networkingv1.AddToScheme(scheme)).To(Succeed())
	g.Expect(controllerv1alpha1.AddToScheme(scheme)).To(Succeed())

	firstRouting := workspaceNameTestRouting("routing-first-route", "workspace-id-first", "real-first-workspace")
	secondRouting := workspaceNameTestRouting("routing-second-route", "workspace-id-second", "real-second-workspace")
	fakeClient := fake.NewClientBuilder().WithScheme(scheme).
		WithStatusSubresource(&controllerv1alpha1.DevWorkspaceRouting{}).
		WithObjects(firstRouting, secondRouting).Build()
	reconciler := &DevWorkspaceRoutingReconciler{
		Client:           fakeClient,
		NonCachingClient: fakeClient,
		Log:              ctrl.Log,
		Scheme:           scheme,
		SolverGetter:     &solvers.SolverGetter{},
	}
	ctx := context.Background()

	for range 3 {
		result, err := reconciler.Reconcile(ctx, ctrl.Request{NamespacedName: client.ObjectKeyFromObject(firstRouting)})
		g.Expect(err).To(Succeed())
		if !result.Requeue {
			break
		}
	}

	service := &corev1.Service{}
	serviceKey := client.ObjectKey{Namespace: firstRouting.Namespace, Name: common.EndpointName("api")}
	g.Expect(fakeClient.Get(ctx, serviceKey, service)).To(Succeed())
	g.Expect(service.Labels).To(HaveKeyWithValue(constants.DevWorkspaceNameLabel, "real-first-workspace"))

	_, err := reconciler.Reconcile(ctx, ctrl.Request{NamespacedName: client.ObjectKeyFromObject(secondRouting)})
	g.Expect(err).To(Succeed())
	storedRouting := &controllerv1alpha1.DevWorkspaceRouting{}
	g.Expect(fakeClient.Get(ctx, client.ObjectKeyFromObject(secondRouting), storedRouting)).To(Succeed())
	g.Expect(storedRouting.Status.Phase).To(Equal(controllerv1alpha1.RoutingFailed))
	g.Expect(storedRouting.Status.Message).To(ContainSubstring("real-first-workspace"))
	g.Expect(storedRouting.Status.Message).NotTo(ContainSubstring(firstRouting.Name))
}

