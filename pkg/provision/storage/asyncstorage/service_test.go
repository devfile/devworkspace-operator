func TestSyncWorkspaceSyncServiceRepairsHiddenServiceWithEmptyWorkspaceID(t *testing.T) {
	ctx := context.Background()
	scheme := runtime.NewScheme()
	if err := appsv1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	if err := corev1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	deployment := &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: asyncServerDeploymentName, Namespace: "ns", UID: "async-deployment"},
		Spec:       appsv1.DeploymentSpec{Selector: &metav1.LabelSelector{MatchLabels: map[string]string{"app": "async-storage"}}},
	}
	desired := getWorkspaceSyncServiceSpec(deployment)
	existing := desired.DeepCopy()
	existing.UID = "existing-service"
	existing.ResourceVersion = "17"
	existing.Spec.ClusterIP = "10.0.0.21"
	delete(existing.Labels, constants.DevWorkspaceIDLabel)
	if err := controllerutil.SetOwnerReference(deployment, existing, scheme); err != nil {
		t.Fatal(err)
	}
	backing := fake.NewClientBuilder().WithScheme(scheme).WithObjects(existing).Build()
	cached := &asyncServiceCountingClient{Client: backing, hideUnlabeledServices: true}
	fresh := &asyncServiceCountingClient{Client: backing}
	api := sync.ClusterAPI{Client: cached, NonCachingClient: fresh, Scheme: scheme, Logger: logr.Discard(), Ctx: ctx}

	service, err := SyncWorkspaceSyncServiceToCluster(deployment, api)
	if !errors.Is(err, NotReadyError) {
		t.Fatalf("want not-ready while repairing Service, got service=%#v err=%v", service, err)
	}
	if service != nil {
		t.Fatalf("want nil Service until the update is observed, got %#v", service)
	}
	if cached.gets != 1 || fresh.gets != 1 || cached.creates != 1 || cached.updates != 1 || cached.deletes != 0 {
		t.Fatalf("want cached create/update and one fresh read; cached=%+v fresh=%+v", cached, fresh)
	}

	actual := &corev1.Service{}
	if err := backing.Get(ctx, client.ObjectKeyFromObject(existing), actual); err != nil {
		t.Fatal(err)
	}
	if label, ok := actual.Labels[constants.DevWorkspaceIDLabel]; !ok || label != "" {
		t.Fatalf("empty workspace ID label was not restored: labels=%v", actual.Labels)
	}
	if actual.UID != existing.UID || actual.Spec.ClusterIP != existing.Spec.ClusterIP {
		t.Fatalf("Service identity or ClusterIP changed: uid=%q clusterIP=%q", actual.UID, actual.Spec.ClusterIP)
	}
	if cached.lastUpdateResourceVersion != existing.ResourceVersion {
		t.Fatalf("Service update did not preserve the existing resourceVersion: got %q, want %q", cached.lastUpdateResourceVersion, existing.ResourceVersion)
	}
	if len(actual.OwnerReferences) != 1 || actual.OwnerReferences[0].UID != deployment.UID || actual.OwnerReferences[0].Kind != "Deployment" {
		t.Fatalf("expected async Deployment owner reference to remain: %#v", actual.OwnerReferences)
	}

	service, err = SyncWorkspaceSyncServiceToCluster(deployment, api)
	if err != nil {
		t.Fatalf("second sync did not converge: %v", err)
	}
	if service == nil || service.UID != existing.UID || service.Spec.ClusterIP != existing.Spec.ClusterIP {
		t.Fatalf("second sync returned unexpected Service: %#v", service)
	}
	if cached.gets != 2 || fresh.gets != 1 || cached.creates != 1 || cached.updates != 1 || cached.deletes != 0 {
		t.Fatalf("converged sync wrote or reread the Service: cached=%+v fresh=%+v", cached, fresh)
	}
}

// Generated by Codex
func TestSyncWorkspaceSyncServiceRejectsForeignHiddenService(t *testing.T) {
	ctx := context.Background()
	scheme := runtime.NewScheme()
	if err := appsv1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	if err := corev1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	deployment := &appsv1.Deployment{
		ObjectMeta: metav1.ObjectMeta{Name: asyncServerDeploymentName, Namespace: "ns", UID: "async-deployment"},
		Spec:       appsv1.DeploymentSpec{Selector: &metav1.LabelSelector{MatchLabels: map[string]string{"app": "async-storage"}}},
	}
	foreignController := metav1.OwnerReference{APIVersion: "apps/v1", Kind: "Deployment", Name: "foreign", UID: "foreign-deployment", Controller: ptr.To(true)}
	foreign := &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{
			Name:            asyncServerServiceName,
			Namespace:       "ns",
			UID:             "foreign-service",
			ResourceVersion: "23",
			Labels:          map[string]string{"app.kubernetes.io/name": "async-storage"},
			OwnerReferences: []metav1.OwnerReference{foreignController},
		},
		Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "foreign"}},
	}
	backing := fake.NewClientBuilder().WithScheme(scheme).WithObjects(foreign).Build()
	cached := &asyncServiceCountingClient{Client: backing, hideUnlabeledServices: true}
	fresh := &asyncServiceCountingClient{Client: backing}
	api := sync.ClusterAPI{Client: cached, NonCachingClient: fresh, Scheme: scheme, Logger: logr.Discard(), Ctx: ctx}

	_, err := SyncWorkspaceSyncServiceToCluster(deployment, api)
	var unrecoverable *sync.UnrecoverableSyncError
	if !errors.As(err, &unrecoverable) {
		t.Fatalf("want permanent sync failure for foreign Service, got %v", err)
	}
	if cached.gets != 1 || fresh.gets != 1 {
		t.Fatalf("want cache miss and one authoritative read; cached=%+v fresh=%+v", cached, fresh)
	}
	if cached.creates != 1 || cached.updates != 0 || cached.deletes != 0 || fresh.updates != 0 || fresh.deletes != 0 {
		t.Fatalf("foreign collision caused unexpected writes: cached=%+v fresh=%+v", cached, fresh)
	}

	actual := &corev1.Service{}
	if err := backing.Get(ctx, client.ObjectKeyFromObject(foreign), actual); err != nil {
		t.Fatalf("foreign Service was deleted: %v", err)
	}
	if !reflect.DeepEqual(foreign, actual) {
		t.Fatalf("foreign Service was modified:\nwant: %#v\n got: %#v", foreign, actual)
	}
}

// Generated by Codex
type asyncServiceCountingClient struct {
	client.Client
	gets, creates, updates, deletes int
	hideUnlabeledServices           bool
	lastUpdateResourceVersion       string
}

// Generated by Codex
func (c *asyncServiceCountingClient) Get(ctx context.Context, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
	if _, ok := obj.(*corev1.Service); ok {
		c.gets++
	}
	if err := c.Client.Get(ctx, key, obj, opts...); err != nil {
		return err
	}
	if _, isService := obj.(*corev1.Service); isService && c.hideUnlabeledServices {
		if _, labeled := obj.GetLabels()[constants.DevWorkspaceIDLabel]; !labeled {
			return apierrors.NewNotFound(schema.GroupResource{Resource: "services"}, key.Name)
		}
	}
	return nil
}

// Generated by Codex
func (c *asyncServiceCountingClient) Create(ctx context.Context, obj client.Object, opts ...client.CreateOption) error {
	if _, ok := obj.(*corev1.Service); ok {
		c.creates++
	}
	return c.Client.Create(ctx, obj, opts...)
}

// Generated by Codex
func (c *asyncServiceCountingClient) Update(ctx context.Context, obj client.Object, opts ...client.UpdateOption) error {
	if _, ok := obj.(*corev1.Service); ok {
		c.updates++
		c.lastUpdateResourceVersion = obj.GetResourceVersion()
	}
	return c.Client.Update(ctx, obj, opts...)
}

