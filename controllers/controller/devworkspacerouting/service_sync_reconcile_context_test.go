func TestReconcileReturnsServiceSyncContextErrors(t *testing.T) {
	for _, test := range []struct {
		name  string
		cause error
	}{
		{name: "canceled", cause: context.Canceled},
		{name: "deadline exceeded", cause: context.DeadlineExceeded},
	} {
		t.Run(test.name, func(t *testing.T) {
			infrastructure.InitializeForTesting(infrastructure.Kubernetes)
			routing := serviceSyncContextRouting()
			backing := fake.NewClientBuilder().WithScheme(routingTestScheme(t)).WithStatusSubresource(routing).WithObjects(routing).Build()
			deadline := time.Now().Add(time.Minute)
			ctx, cancel := context.WithDeadline(context.WithValue(context.Background(), testContextKey{}, "reconcile-context"), deadline)
			defer cancel()
			injectedErr := fmt.Errorf("guarded Service GET failed: %w", test.cause)
			tracker := &serviceSyncReconcileTracker{err: injectedErr}
			cached := serviceSyncReconcileClient{Client: backing, tracker: tracker}
			fresh := serviceSyncReconcileClient{Client: backing, tracker: tracker, fresh: true}
			reconciler := DevWorkspaceRoutingReconciler{
				Client: cached, NonCachingClient: fresh, Scheme: routingTestScheme(t),
				Log: logr.Discard(), SolverGetter: &solvers.SolverGetter{},
			}

			result, err := reconciler.Reconcile(ctx, ctrl.Request{NamespacedName: client.ObjectKeyFromObject(routing)})
			if err != injectedErr || !errors.Is(err, test.cause) {
				t.Fatalf("want original wrapped %v error %v, got result=%#v err=%v", test.cause, injectedErr, result, err)
			}
			if result != (ctrl.Result{}) {
				t.Fatalf("context error returned non-empty reconcile result: %#v", result)
			}
			if tracker.contextValue != "reconcile-context" || !tracker.hasDeadline || !tracker.deadline.Equal(deadline) {
				t.Fatalf("guarded Service GET did not receive reconcile context: %#v", tracker)
			}
			if !reflect.DeepEqual(tracker.operations, []string{"list", "get"}) {
				t.Fatalf("operations continued after guarded Service GET failed: %v", tracker.operations)
			}
			if tracker.statusCalls != 0 || tracker.statusUpdates != 0 || tracker.serviceCreates != 0 || tracker.serviceUpdates != 0 || tracker.serviceDeletes != 0 {
				t.Fatalf("context error caused later status or Service writes: %#v", tracker)
			}
			assertServiceSyncContextUnchanged(t, backing, routing)
		})
	}
}

