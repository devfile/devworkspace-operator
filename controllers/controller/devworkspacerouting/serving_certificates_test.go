	wrongNamespace.Namespace = "other-ns"
	wrongNamespaceClient := fake.NewClientBuilder().WithScheme(scheme).WithObjects(wrongNamespace).Build()
	r.NonCachingClient = wrongNamespaceClient
	err := r.validateServingCertificates(ctx, []corev1.Service{service})
	var notReady *solvers.RoutingNotReady
	if !errors.As(err, &notReady) {
		t.Fatalf("Secret in another namespace should be treated as missing, got %v", err)
	}
