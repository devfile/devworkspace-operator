func TestGenericServiceSyncUsesCachedClient(t *testing.T) {
	for _, metadata := range []string{"ordinary", "discoverable", "routing owner"} {
		t.Run(metadata, func(t *testing.T) {
			scheme := runtime.NewScheme()
			if err := corev1.AddToScheme(scheme); err != nil {
				t.Fatal(err)
			}
			desired := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns"}, Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "new"}}}
			if metadata == "discoverable" {
				desired.Annotations = map[string]string{constants.DevWorkspaceDiscoverableServiceAnnotation: "true"}
			}
			if metadata == "routing owner" {
				desired.OwnerReferences = []metav1.OwnerReference{{Kind: "DevWorkspaceRouting", UID: "mine", Controller: ptr.To(true)}}
			}
			backing := fake.NewClientBuilder().WithScheme(scheme).Build()
			cached := &countingServiceClient{Client: backing}
			fresh := &countingServiceClient{Client: backing}
			_, err := SyncObjectWithCluster(desired, ClusterAPI{Client: cached, NonCachingClient: fresh, Ctx: context.Background(), Logger: logr.Discard()})
			var pending *NotInSyncError
			if !errors.As(err, &pending) || pending.Reason != CreatedObjectReason {
				t.Fatalf("want created object, got %v", err)
			}
			if cached.gets != 1 || fresh.gets != 0 || cached.creates != 1 || fresh.creates != 0 {
				t.Fatalf("want one cached GET and cached create; cached=%+v fresh=%+v", cached, fresh)
			}
			existing := desired.DeepCopy()
			existing.OwnerReferences = []metav1.OwnerReference{{Kind: "DevWorkspaceRouting", UID: "foreign", Controller: ptr.To(true)}}
			existing.Spec.Selector["app"] = "old"
			if err := backing.Update(context.Background(), existing); err != nil {
				t.Fatal(err)
			}
			cached.gets = 0
			_, err = SyncObjectWithCluster(desired, ClusterAPI{Client: cached, NonCachingClient: fresh, Ctx: context.Background(), Logger: logr.Discard()})
			if !errors.As(err, &pending) || pending.Reason != UpdatedObjectReason {
				t.Fatalf("want generic update regardless of routing ownership, got %v", err)
			}
			if cached.gets != 1 || fresh.gets != 0 || cached.updates != 1 || fresh.updates != 0 {
				t.Fatalf("want one cached GET and cached update; cached=%+v fresh=%+v", cached, fresh)
			}
			actual := &corev1.Service{}
			if err := backing.Get(context.Background(), client.ObjectKeyFromObject(desired), actual); err != nil {
				t.Fatal(err)
			}
			if actual.Spec.Selector["app"] != "new" {
				t.Fatalf("generic Service update not persisted: %#v", actual)
			}
		})
	}
}

func TestRoutingServiceSyncReadsOnceAndWritesThroughCachedClient(t *testing.T) {
	for _, freshReader := range []bool{false, true} {
		for _, exists := range []bool{false, true} {
			name := fmt.Sprintf("fresh=%t/exists=%t", freshReader, exists)
			t.Run(name, func(t *testing.T) {
				scheme := runtime.NewScheme()
				if err := corev1.AddToScheme(scheme); err != nil {
					t.Fatal(err)
				}
				desired := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns", Labels: map[string]string{constants.DevWorkspaceIDLabel: "mine"}}, Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "new"}}}
				backing := fake.NewClientBuilder().WithScheme(scheme).Build()
				if exists {
					existing := desired.DeepCopy()
					existing.Spec.Selector["app"] = "old"
					existing.Spec.ClusterIP = "10.0.0.1"
					if err := backing.Create(context.Background(), existing); err != nil {
						t.Fatal(err)
					}
				}
				cached := &countingServiceClient{Client: backing}
				fresh := &countingServiceClient{Client: backing}
				api := ClusterAPI{Client: cached, Ctx: context.Background(), Logger: logr.Discard()}
				if freshReader {
					api.NonCachingClient = fresh
				}
				_, err := SyncRoutingServiceWithCluster(desired, api)
				var pending *NotInSyncError
				wantReason := CreatedObjectReason
				if exists {
					wantReason = UpdatedObjectReason
				}
				if !errors.As(err, &pending) || pending.Reason != wantReason {
					t.Fatalf("want %s, got %v", wantReason, err)
				}
				wantCachedGets, wantFreshGets := 1, 0
				if freshReader {
					wantCachedGets, wantFreshGets = 0, 1
				}
				wantCreates, wantUpdates := 1, 0
				if exists {
					wantCreates, wantUpdates = 0, 1
				}
				if cached.gets != wantCachedGets || fresh.gets != wantFreshGets || cached.creates != wantCreates || cached.updates != wantUpdates || fresh.creates != 0 || fresh.updates != 0 {
					t.Fatalf("unexpected reads/writes: cached=%+v fresh=%+v", cached, fresh)
				}
				actual := &corev1.Service{}
				if err := backing.Get(context.Background(), client.ObjectKeyFromObject(desired), actual); err != nil {
					t.Fatal(err)
				}
				if actual.Spec.Selector["app"] != "new" || exists && actual.Spec.ClusterIP != "10.0.0.1" {
					t.Fatalf("Service not synchronized in place: %#v", actual)
				}
				cached.gets, fresh.gets = 0, 0
				if _, err := SyncRoutingServiceWithCluster(desired, api); err != nil {
					t.Fatalf("second sync did not converge: %v", err)
				}
				if cached.gets != wantCachedGets || fresh.gets != wantFreshGets || cached.creates != wantCreates || cached.updates != wantUpdates {
					t.Fatalf("converged sync reread or wrote Service: cached=%+v fresh=%+v", cached, fresh)
				}
			})
		}
	}
}

type countingServiceClient struct {
	client.Client
	gets, creates, updates, deletes int
	lastUpdate                      client.Object
}

func (c *countingServiceClient) Get(ctx context.Context, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
	c.gets++
	return c.Client.Get(ctx, key, obj, opts...)
}

func (c *countingServiceClient) Create(ctx context.Context, obj client.Object, opts ...client.CreateOption) error {
	c.creates++
	return c.Client.Create(ctx, obj, opts...)
}

func (c *countingServiceClient) Update(ctx context.Context, obj client.Object, opts ...client.UpdateOption) error {
	c.updates++
	c.lastUpdate = obj.DeepCopyObject().(client.Object)
	return c.Client.Update(ctx, obj, opts...)
}

