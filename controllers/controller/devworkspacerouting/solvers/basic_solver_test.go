func testEndpoint(name string, port int, exposure controllerv1alpha1.EndpointExposure, discoverable bool, protocol controllerv1alpha1.EndpointProtocol) controllerv1alpha1.Endpoint {
	attributes := controllerv1alpha1.Attributes{}
	if discoverable {
		attributes.PutBoolean(string(controllerv1alpha1.DiscoverableAttribute), true)
	}
	return controllerv1alpha1.Endpoint{Name: name, TargetPort: port, Exposure: exposure, Protocol: protocol, Attributes: attributes}
}

