func TestBasicSolverGetSpecObjectsErrors(t *testing.T) {
	sentinel := errors.New("injected Service lookup failure")
	tests := []struct {
		name      string
		endpoints map[string]controllerv1alpha1.EndpointList
		objects   []client.Object
		failGet   bool
		checkErr  func(*testing.T, error)
	}{
		{
			name:      "foreign Service conflict",
			endpoints: map[string]controllerv1alpha1.EndpointList{"main": {testEndpoint("my--api", 8080, controllerv1alpha1.PublicEndpointExposure, true, "http")}},
			objects: []client.Object{&corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "my-api", Namespace: "workspace-namespace", Labels: map[string]string{
				constants.DevWorkspaceIDLabel: "other-id", constants.DevWorkspaceNameLabel: "other-workspace",
			}}}},
			checkErr: func(t *testing.T, err error) {
				var conflict *ServiceConflictError
				if !errors.As(err, &conflict) || conflict.EndpointName != "my--api" || conflict.WorkspaceName != "other-workspace" || err.Error() != "discoverable endpoint 'my--api' is already in use by workspace 'other-workspace'" {
					t.Fatalf("unexpected conflict error: %v", err)
				}
			},
		},
		{
			name: "normalized duplicate names",
			endpoints: map[string]controllerv1alpha1.EndpointList{
				"first":  {testEndpoint("my--api", 8080, controllerv1alpha1.PublicEndpointExposure, true, "http")},
				"second": {testEndpoint("my-api", 8081, controllerv1alpha1.InternalEndpointExposure, true, "tcp")},
			},
			checkErr: func(t *testing.T, err error) {
				var duplicate *DuplicateEndpointError
				if !errors.As(err, &duplicate) || duplicate.EndpointName != "my-api" || err.Error() != "discoverable endpoints 'my--api' and 'my-api' both normalize to Service name 'my-api'" {
					t.Fatalf("unexpected duplicate error: %v", err)
				}
			},
		},
		{
			name:      "reserved aggregate Service name",
			endpoints: map[string]controllerv1alpha1.EndpointList{"main": {testEndpoint("workspace-id-service", 8080, controllerv1alpha1.InternalEndpointExposure, true, "tcp")}},
			checkErr: func(t *testing.T, err error) {
				var invalid *RoutingInvalid
				if !errors.As(err, &invalid) || invalid.Reason != "discoverable endpoint 'workspace-id-service' uses reserved Service name 'workspace-id-service'" || err.Error() != "workspace routing is invalid: discoverable endpoint 'workspace-id-service' uses reserved Service name 'workspace-id-service'" {
					t.Fatalf("unexpected reserved-name error: %v", err)
				}
			},
		},
		{
			name:      "Service GET failure",
			endpoints: map[string]controllerv1alpha1.EndpointList{"main": {testEndpoint("my--api", 8080, controllerv1alpha1.PublicEndpointExposure, true, "http")}},
			failGet:   true,
			checkErr: func(t *testing.T, err error) {
				if err != sentinel {
					t.Fatalf("error = %v, want sentinel %v", err, sentinel)
				}
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var getErr error
			if tt.failGet {
				getErr = sentinel
			}
			solver, meta := newBasicSolverTest(t, getErr, tt.objects...)
			objects, err := solver.GetSpecObjects(context.Background(), routingForEndpoints(tt.endpoints), meta)
			if err == nil {
				t.Fatal("GetSpecObjects() returned no error")
			}
			tt.checkErr(t, err)
			if !reflect.DeepEqual(objects, RoutingObjects{}) {
				t.Fatalf("error returned partial routing objects: %#v", objects)
			}
		})
	}
}

