func TestClusterSolverGetSpecObjectsServingCertMounts(t *testing.T) {
	workspaceMeta := DevWorkspaceMetadata{
		DevWorkspaceId:   "workspace-id",
		DevWorkspaceName: "workspace",
		Namespace:        "workspace-namespace",
		PodSelector:      map[string]string{"workspace": "workspace-id"},
	}
	endpoints := map[string]controllerv1alpha1.EndpointList{
		"main": {
			{
				Name:       "api",
				TargetPort: 8080,
				Exposure:   controllerv1alpha1.PublicEndpointExposure,
				Attributes: controllerv1alpha1.Attributes{}.
					PutBoolean(string(controllerv1alpha1.DiscoverableAttribute), true),
			},
			{
				Name:       "database",
				TargetPort: 5432,
				Exposure:   controllerv1alpha1.InternalEndpointExposure,
				Attributes: controllerv1alpha1.Attributes{}.
					PutBoolean(string(controllerv1alpha1.DiscoverableAttribute), true),
			},
		},
	}
	aggregateServiceName := common.ServiceName(workspaceMeta.DevWorkspaceId)

	tests := []struct {
		name           string
		tls            bool
		expectedMounts map[string]string
	}{
		{
			name: "TLS discoverable endpoint certificates use distinct mounts",
			tls:  true,
			expectedMounts: map[string]string{
				"/var/serving-cert/":          aggregateServiceName,
				"/var/serving-cert/api/":      "api",
				"/var/serving-cert/database/": "database",
			},
		},
		{
			name: "plaintext routing requests no certificates",
			tls:  false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			scheme := runtime.NewScheme()
			assert.NoError(t, corev1.AddToScheme(scheme))
			solver := NewClusterSolver(fake.NewClientBuilder().WithScheme(scheme).Build(), tt.tls)
			routing := &controllerv1alpha1.DevWorkspaceRouting{
				Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{
					Endpoints:   endpoints,
					PodSelector: workspaceMeta.PodSelector,
				},
			}

			objects, err := solver.GetSpecObjects(routing, workspaceMeta)
			if !assert.NoError(t, err) {
				return
			}

			if !tt.tls {
				assert.Empty(t, objects.PodAdditions.Volumes)
				assert.Empty(t, objects.PodAdditions.VolumeMounts)
				return
			}

			assert.Len(t, objects.Services, 3)
			for _, service := range objects.Services {
				assert.Equal(t, service.Name, service.Annotations[serviceServingCertAnnot])
			}

			volumeSecrets := make(map[string]string, len(objects.PodAdditions.Volumes))
			for _, volume := range objects.PodAdditions.Volumes {
				volumeSecrets[volume.Name] = volume.Secret.SecretName
			}

			actualMounts := make(map[string]string, len(objects.PodAdditions.VolumeMounts))
			for _, mount := range objects.PodAdditions.VolumeMounts {
				if _, exists := actualMounts[mount.MountPath]; exists {
					assert.Failf(t, "duplicate serving certificate mount path", "path %q is used more than once", mount.MountPath)
				}
				actualMounts[mount.MountPath] = volumeSecrets[mount.Name]
			}

			assert.Len(t, actualMounts, 3)
			assert.Equal(t, tt.expectedMounts, actualMounts)
		})
	}
}

