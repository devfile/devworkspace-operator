// Generated by Codex.
func servingCertSecretWithData(service corev1.Service, data map[string][]byte, annotations ...map[string]string) *corev1.Secret {
	secretAnnotations := map[string]string{}
	if len(annotations) > 0 {
		secretAnnotations = annotations[0]
	} else {
		secretAnnotations = map[string]string{
			servingServiceBetaName: service.Name,
			servingServiceBetaUID:  string(service.UID),
		}
	}
	return &corev1.Secret{
		ObjectMeta: metav1.ObjectMeta{
			Name: service.Name, Namespace: service.Namespace, Annotations: secretAnnotations,
			OwnerReferences: []metav1.OwnerReference{{APIVersion: "v1", Kind: "Service", Name: service.Name, UID: service.UID}},
		},
		Type: corev1.SecretTypeTLS,
		Data: data,
	}
}

