func recoveryRouting(generation int64) *controllerv1alpha1.DevWorkspaceRouting {
	return &controllerv1alpha1.DevWorkspaceRouting{
		ObjectMeta: metav1.ObjectMeta{Name: "routing-mine", Namespace: "ns", UID: "mine-routing", Generation: generation},
		Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{
			DevWorkspaceId: "mine", RoutingClass: controllerv1alpha1.DevWorkspaceRoutingCluster,
			Endpoints: map[string]controllerv1alpha1.EndpointList{"main": recoveryEndpoints("api")},
		},
	}
}

// Generated by Codex
func recoveryEndpoints(names ...string) controllerv1alpha1.EndpointList {
	endpoints := make(controllerv1alpha1.EndpointList, len(names))
	for i, name := range names {
		endpoints[i] = controllerv1alpha1.Endpoint{
			Name: name, TargetPort: 8080, Exposure: controllerv1alpha1.InternalEndpointExposure,
			Attributes: controllerv1alpha1.Attributes{}.PutBoolean("discoverable", true),
		}
	}
	return endpoints
}

