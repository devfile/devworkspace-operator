func TestGenericServiceCollisionRepairsOwnedService(t *testing.T) {
	for _, owner := range []string{"DevWorkspace", "Deployment", "controller"} {
		t.Run(owner, func(t *testing.T) {
			desired, existing := collisionServices()
			if owner == "Deployment" {
				desired.OwnerReferences[0] = metav1.OwnerReference{APIVersion: "apps/v1", Kind: "Deployment", Name: "async", UID: "deployment-uid", Controller: ptr.To(false)}
				desired.Labels[constants.DevWorkspaceIDLabel] = ""
			}
			if owner == "controller" {
				desired.OwnerReferences[0].Controller = ptr.To(true)
			}
			existing.OwnerReferences = append([]metav1.OwnerReference(nil), desired.OwnerReferences...)
			backing := fake.NewClientBuilder().WithObjects(existing).Build()
			cached := &countingServiceClient{Client: filteredServiceClient{backing}}
			fresh := &countingServiceClient{Client: backing}
			api := ClusterAPI{Client: cached, NonCachingClient: fresh, Ctx: context.Background(), Logger: logr.Discard()}
			_, err := SyncObjectWithCluster(desired, api)
			var pending *NotInSyncError
			if !errors.As(err, &pending) || pending.Reason != UpdatedObjectReason {
				t.Fatalf("want in-place label repair, got %v", err)
			}
			sent := cached.lastUpdate.(*corev1.Service)
			if sent.UID != existing.UID || sent.ResourceVersion != existing.ResourceVersion || sent.Spec.ClusterIP != existing.Spec.ClusterIP {
				t.Fatalf("update lost Service identity: %#v", sent)
			}
			actual := &corev1.Service{}
			if err := backing.Get(api.Ctx, client.ObjectKeyFromObject(existing), actual); err != nil {
				t.Fatal(err)
			}
			label, present := actual.Labels[constants.DevWorkspaceIDLabel]
			if !present || label != desired.Labels[constants.DevWorkspaceIDLabel] || actual.UID != existing.UID || actual.Spec.ClusterIP != existing.Spec.ClusterIP {
				t.Fatalf("owned Service was not repaired: %#v", actual)
			}
			obj, err := SyncObjectWithCluster(desired, api)
			if err != nil || obj == nil {
				t.Fatalf("second call did not converge: obj=%v err=%v", obj, err)
			}
			if cached.gets != 2 || cached.creates != 1 || cached.updates != 1 || cached.deletes != 0 || fresh.gets != 1 || fresh.updates != 0 {
				t.Fatalf("unexpected recovery calls: cached=%+v fresh=%+v", cached, fresh)
			}
		})
	}
}

