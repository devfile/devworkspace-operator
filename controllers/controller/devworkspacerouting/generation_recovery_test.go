func TestFailedRoutingRemainsTerminalWhenForeignServiceIsRemoved(t *testing.T) {
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	routing := recoveryRouting(1)
	foreign := &corev1.Service{
		ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: routing.Namespace, UID: "foreign-service"},
		Spec:       corev1.ServiceSpec{Selector: map[string]string{"app": "foreign"}},
	}
	r, backing := recoveryReconciler(t, routing, foreign)
	r.Client = serviceLabelFilteredClient{Client: backing}
	if _, err := r.Reconcile(context.Background(), recoveryRequest(routing)); err != nil {
		t.Fatal(err)
	}
	failed := getRouting(t, backing, routing)
	if failed.Status.Phase != controllerv1alpha1.RoutingFailed || failed.Status.ObservedGeneration != 1 {
		t.Fatalf("foreign Service collision did not fail generation 1: %#v", failed.Status)
	}
	if err := backing.Delete(context.Background(), foreign); err != nil {
		t.Fatal(err)
	}
	recorder := &generationRecordingClient{Client: serviceLabelFilteredClient{Client: backing}}
	r.Client = recorder
	r.NonCachingClient = backing
	if _, err := r.Reconcile(context.Background(), recoveryRequest(routing)); err != nil {
		t.Fatal(err)
	}
	stored := getRouting(t, backing, routing)
	if stored.Status.Phase != controllerv1alpha1.RoutingFailed || stored.Status.Message != failed.Status.Message || stored.Status.ObservedGeneration != 1 {
		t.Fatalf("same-generation failure should remain terminal: %#v", stored.Status)
	}
	if recorder.statusUpdates != 0 || recorder.serviceCreates != 0 {
		t.Fatalf("terminal failure wrote status %d times or created %d Services", recorder.statusUpdates, recorder.serviceCreates)
	}
	if err := backing.Get(context.Background(), client.ObjectKey{Namespace: routing.Namespace, Name: "api"}, &corev1.Service{}); err == nil {
		t.Fatal("terminal failed routing created a Service after conflict removal")
	}
}

