func TestDiscoverableEndpointContract(t *testing.T) {
	ctx := context.Background()
	scheme := runtime.NewScheme()
	require.NoError(t, dwv2.AddToScheme(scheme))
	require.NoError(t, corev1.AddToScheme(scheme))
	registration := &endpointIndexRegistration{}
	require.NoError(t, RegisterDiscoverableEndpointIndex(ctx, registration))
	serviceClient := fake.NewClientBuilder().WithScheme(scheme).Build()

	exposures := []struct {
		name     string
		value    dwv2.EndpointExposure
		eligible bool
	}{
		{"omitted", "", true},
		{"internal", dwv2.InternalEndpointExposure, true},
		{"public", dwv2.PublicEndpointExposure, true},
		{"none", dwv2.NoneEndpointExposure, false},
	}
	// Malformed values cover defensive in-memory behavior, not CRD acceptance.
	discoverability := []struct {
		name     string
		raw      string
		eligible bool
	}{
		{"absent", "", false},
		{"empty-map", "", false},
		{"boolean-true", "true", true},
		{"boolean-false", "false", false},
		{"string-true", `"true"`, true},
		{"string-TRUE", `"TRUE"`, true},
		{"string-1", `"1"`, true},
		{"string-false", `"false"`, false},
		{"string-0", `"0"`, false},
		{"string-invalid", `"invalid"`, false},
		{"number", "1", false},
		{"null", "null", false},
		{"object", `{}`, false},
		{"array", `[]`, false},
	}
	names := []struct {
		raw     string
		service string
	}{
		{"api", "api"},
		{"my--endpoint", "my-endpoint"},
	}

	for _, name := range names {
		for _, exposure := range exposures {
			for _, discoverable := range discoverability {
				t.Run(name.raw+"/"+exposure.name+"/"+discoverable.name, func(t *testing.T) {
					workspace := setupWorkspace(t, "varied", "varied-uid", "test-namespace")
					endpoint := workspace.Spec.Template.Components[0].Container.Endpoints[0]
					endpoint.Name = name.raw
					endpoint.Exposure = exposure.value
					endpoint.Attributes = nil
					if discoverable.name == "empty-map" {
						endpoint.Attributes = attributes.Attributes{}
					} else if discoverable.raw != "" {
						endpoint.Attributes = attributes.Attributes{
							"discoverable": apiextv1.JSON{Raw: []byte(discoverable.raw)},
						}
					}
					workspace.Spec.Template.Components[0].Container.Endpoints = []dwv2.Endpoint{endpoint}
					eligible := exposure.eligible && discoverable.eligible
					var expected []string
					if eligible {
						expected = []string{name.service}
					}

					t.Run("index", func(t *testing.T) {
						require.ElementsMatch(t, expected, registration.extract(workspace))
					})
					t.Run("solver", func(t *testing.T) {
						services, err := solvers.GetDiscoverableServicesForEndpoints(
							map[string]controllerv1alpha1.EndpointList{
								"test-component": conversion.ConvertAllDevfileEndpoints(workspace.Spec.Template.Components[0].Container.Endpoints),
							}, solvers.DevWorkspaceMetadata{
								DevWorkspaceId: "workspace-contract", DevWorkspaceName: workspace.Name, Namespace: workspace.Namespace,
							}, serviceClient)
						require.NoError(t, err)
						var serviceNames []string
						for _, service := range services {
							serviceNames = append(serviceNames, service.Name)
						}
						require.ElementsMatch(t, expected, serviceNames)
					})

					for _, variedSide := range []string{"incoming", "peer"} {
						t.Run(variedSide, func(t *testing.T) {
							incoming := setupWorkspace(t, "incoming", "incoming-uid", workspace.Namespace)
							peer := setupWorkspace(t, "peer", "peer-uid", workspace.Namespace)
							fixed := endpoint
							fixed.Name = name.service
							fixed.Exposure = dwv2.PublicEndpointExposure
							fixed.Attributes = attributes.Attributes{}.PutBoolean("discoverable", true)
							incoming.Spec.Template.Components[0].Container.Endpoints = []dwv2.Endpoint{fixed}
							peer.Spec.Template.Components[0].Container.Endpoints = []dwv2.Endpoint{fixed}
							if variedSide == "incoming" {
								incoming.Spec.Template.Components[0].Container.Endpoints = []dwv2.Endpoint{endpoint}
							} else {
								peer.Spec.Template.Components[0].Container.Endpoints = []dwv2.Endpoint{endpoint}
							}
							handler := &WebhookHandler{
								Client:  newIndexedWorkspaceClientBuilder(t, scheme).WithObjects(peer).Build(),
								Decoder: admission.NewDecoder(scheme),
							}
							response := handler.ValidateDevfile(ctx, admission.Request{AdmissionRequest: admissionv1.AdmissionRequest{
								Operation: admissionv1.Create, Namespace: incoming.Namespace, Object: newRawExtension(t, incoming),
							}})
							require.Equal(t, !eligible, response.Allowed)
							if eligible {
								require.Contains(t, response.Result.Message, (&solvers.ServiceConflictError{
									EndpointName: peer.Spec.Template.Components[0].Container.Endpoints[0].Name, WorkspaceName: peer.Name,
								}).Error())
							}
						})
					}
				})
			}
		}
	}
}
