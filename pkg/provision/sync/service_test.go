// filteredServiceClient models the production cache's workspace-label filter.
type filteredServiceClient struct{ client.Client }

func (c filteredServiceClient) Get(ctx context.Context, key client.ObjectKey, obj client.Object, opts ...client.GetOption) error {
	if err := c.Client.Get(ctx, key, obj, opts...); err != nil {
		return err
	}
	_, labeled := obj.GetLabels()[constants.DevWorkspaceIDLabel]
	if _, ok := obj.(*corev1.Service); ok && !labeled {
		return apierrors.NewNotFound(schema.GroupResource{Resource: "services"}, key.Name)
	}
	return nil
}

