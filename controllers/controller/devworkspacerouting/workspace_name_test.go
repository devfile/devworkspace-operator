func TestWorkspaceNameRequiresDevWorkspaceControllerOwner(t *testing.T) {
	controller := true
	nonController := false
	tests := []struct {
		name            string
		ownerReferences []metav1.OwnerReference
		want            string
	}{
		{name: "no owner"},
		{
			name: "non-controller owner",
			ownerReferences: []metav1.OwnerReference{{
				APIVersion: v1alpha2.SchemeGroupVersion.String(),
				Kind:       "DevWorkspace",
				Name:       "ignored-workspace",
				Controller: &nonController,
			}},
		},
		{
			name: "wrong kind",
			ownerReferences: []metav1.OwnerReference{{
				APIVersion: v1alpha2.SchemeGroupVersion.String(),
				Kind:       "Pod",
				Name:       "ignored-pod",
				Controller: &controller,
			}},
		},
		{
			name: "wrong API group",
			ownerReferences: []metav1.OwnerReference{{
				APIVersion: controllerv1alpha1.GroupVersion.String(),
				Kind:       "DevWorkspace",
				Name:       "ignored-workspace",
				Controller: &controller,
			}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			g := NewWithT(t)
			routing := &controllerv1alpha1.DevWorkspaceRouting{ObjectMeta: metav1.ObjectMeta{OwnerReferences: tt.ownerReferences}}
			g.Expect(workspaceName(routing)).To(Equal(tt.want))
		})
	}
}

