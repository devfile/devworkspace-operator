func TestReconcileRepairsOwnedDiscoverableServiceWithStaleWorkspaceID(t *testing.T) {
	tests := []struct {
		name             string
		workspaceIDLabel string
		includeIDLabel   bool
	}{
		{name: "wrong workspace ID label", workspaceIDLabel: "stale-workspace-id", includeIDLabel: true},
		{name: "missing workspace ID label"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			infrastructure.InitializeForTesting(infrastructure.Kubernetes)
			g := NewWithT(t)
			scheme := runtime.NewScheme()
			g.Expect(corev1.AddToScheme(scheme)).To(Succeed())
			g.Expect(networkingv1.AddToScheme(scheme)).To(Succeed())
			g.Expect(controllerv1alpha1.AddToScheme(scheme)).To(Succeed())

			routing := workspaceNameTestRouting("routing-stale-id", "workspace-id", "real-workspace")
			g.Expect(routing.UID).NotTo(BeEmpty())
			serviceLabels := map[string]string{constants.DevWorkspaceNameLabel: "real-workspace"}
			if tt.includeIDLabel {
				serviceLabels[constants.DevWorkspaceIDLabel] = tt.workspaceIDLabel
			}
			controller := true
			discoverableService := &corev1.Service{
				ObjectMeta: metav1.ObjectMeta{
					Name:      common.EndpointName("api"),
					Namespace: routing.Namespace,
					UID:       "existing-service-uid",
					Labels:    serviceLabels,
					OwnerReferences: []metav1.OwnerReference{{
						APIVersion: controllerv1alpha1.GroupVersion.String(),
						Kind:       "DevWorkspaceRouting",
						Name:       routing.Name,
						UID:        routing.UID,
						Controller: &controller,
					}},
				},
				Spec: corev1.ServiceSpec{
					Type:      corev1.ServiceTypeClusterIP,
					ClusterIP: "10.0.0.9",
					Selector:  routing.Spec.PodSelector,
					Ports: []corev1.ServicePort{{
						Name:       common.EndpointName("api"),
						Protocol:   corev1.ProtocolTCP,
						Port:       8080,
						TargetPort: intstr.FromInt(8080),
					}},
				},
			}
			fakeClient := fake.NewClientBuilder().WithScheme(scheme).
				WithStatusSubresource(&controllerv1alpha1.DevWorkspaceRouting{}).
				WithObjects(routing, discoverableService).Build()
			reconciler := &DevWorkspaceRoutingReconciler{
				Client:           fakeClient,
				NonCachingClient: fakeClient,
				Log:              ctrl.Log,
				Scheme:           scheme,
				SolverGetter:     &solvers.SolverGetter{},
			}
			ctx := context.Background()

			for range 3 {
				result, err := reconciler.Reconcile(ctx, ctrl.Request{NamespacedName: client.ObjectKeyFromObject(routing)})
				g.Expect(err).To(Succeed())
				if !result.Requeue {
					break
				}
			}

			storedService := &corev1.Service{}
			serviceKey := client.ObjectKeyFromObject(discoverableService)
			g.Expect(fakeClient.Get(ctx, serviceKey, storedService)).To(Succeed())
			g.Expect(storedService.Labels).To(HaveKeyWithValue(constants.DevWorkspaceIDLabel, routing.Spec.DevWorkspaceId))
			g.Expect(storedService.UID).To(Equal(discoverableService.UID))
			g.Expect(storedService.Spec.ClusterIP).To(Equal(discoverableService.Spec.ClusterIP))
			storedRouting := &controllerv1alpha1.DevWorkspaceRouting{}
			g.Expect(fakeClient.Get(ctx, client.ObjectKeyFromObject(routing), storedRouting)).To(Succeed())
			g.Expect(storedRouting.Status.Phase).NotTo(Equal(controllerv1alpha1.RoutingFailed))
		})
	}
}

