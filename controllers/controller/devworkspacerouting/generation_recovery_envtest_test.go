func deleteGenerationRecoveryObjects(routingName, workspaceID, conflictEndpoint, updatedEndpoint string) {
	for _, object := range []client.Object{
		&controllerv1alpha1.DevWorkspaceRouting{ObjectMeta: metav1.ObjectMeta{Name: routingName, Namespace: testNamespace}},
		&corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: conflictEndpoint, Namespace: testNamespace}},
		&corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: updatedEndpoint, Namespace: testNamespace}},
		&corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: workspaceID + "-service", Namespace: testNamespace}},
	} {
		if object.GetName() == "" {
			continue
		}
		Expect(client.IgnoreNotFound(k8sClient.Delete(context.Background(), object))).To(Succeed())
	}
}
