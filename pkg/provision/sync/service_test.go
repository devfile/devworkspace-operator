func TestSyncDiscoverableServicePreservesForeignService(t *testing.T) {
	for _, scenario := range []string{"hidden by cache", "created after precheck", "matching label with foreign owner", "created during synchronization"} {
		t.Run(scenario, func(t *testing.T) {
			ctx := context.Background()
			scheme := runtime.NewScheme()
			if err := corev1.AddToScheme(scheme); err != nil {
				t.Fatal(err)
			}
			foreign := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns", UID: "foreign-service"}, Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "foreign"}, Ports: []corev1.ServicePort{{Port: 8080}}}}
			desired := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns", Labels: map[string]string{constants.DevWorkspaceIDLabel: "mine"}, Annotations: map[string]string{constants.DevWorkspaceDiscoverableServiceAnnotation: "true"}, OwnerReferences: []metav1.OwnerReference{{APIVersion: "controller.devfile.io/v1alpha1", Kind: "DevWorkspaceRouting", Name: "routing-mine", UID: "mine-routing", Controller: ptr.To(true)}}}, Spec: corev1.ServiceSpec{Selector: map[string]string{"app": "mine"}, Ports: []corev1.ServicePort{{Port: 8080}}}}
			if scenario != "hidden by cache" {
				foreign.Labels = map[string]string{constants.DevWorkspaceIDLabel: "other"}
			}
			if scenario == "matching label with foreign owner" {
				foreign.Labels[constants.DevWorkspaceIDLabel] = "mine"
				foreign.OwnerReferences = []metav1.OwnerReference{{Kind: "DevWorkspaceRouting", UID: "other-routing", Controller: ptr.To(true)}}
			}
			backing := fake.NewClientBuilder().WithScheme(scheme).Build()
			var cached client.Client = backing
			if scenario == "hidden by cache" {
				cached = filteredServiceClient{backing}
			}
			api := ClusterAPI{Client: cached, NonCachingClient: backing, Ctx: ctx, Logger: logr.Discard()}
			if scenario == "created during synchronization" {
				api.Client = serviceCreateRaceClient{Client: backing, foreign: foreign}
			} else if err := backing.Create(ctx, foreign); err != nil {
				t.Fatal(err)
			}
			_, syncErr := SyncRoutingServiceWithCluster(desired, api)
			if syncErr == nil {
				t.Fatal("expected conflict or retry")
			}
			actual := &corev1.Service{}
			if err := backing.Get(ctx, client.ObjectKeyFromObject(foreign), actual); err != nil {
				t.Fatalf("foreign Service deleted: %v", err)
			}
			if !reflect.DeepEqual(actual.Spec, foreign.Spec) || !reflect.DeepEqual(actual.Labels, foreign.Labels) || !reflect.DeepEqual(actual.OwnerReferences, foreign.OwnerReferences) {
				t.Fatalf("foreign Service modified: %#v", actual)
			}
			if scenario == "created during synchronization" {
				var retry *NotInSyncError
				if !errors.As(syncErr, &retry) || retry.Reason != NeedRetryReason {
					t.Fatalf("want retry on create race, got %v", syncErr)
				}
				_, syncErr = SyncRoutingServiceWithCluster(desired, api)
			}
			var fatal *UnrecoverableSyncError
			if !errors.As(syncErr, &fatal) {
				t.Fatalf("want permanent Service conflict, got %v", syncErr)
			}
		})
	}
}

