var _ = Describe("failed routing generation recovery", func() {
	It("retries a failed routing after an endpoint change and leaves the foreign Service unchanged", func() {
		const routingName = "generation-recovery-routing"
		const workspaceID = "generation-recovery"
		const conflictEndpoint = "generation-conflict"
		const updatedEndpoint = "generation-recovered"
		const namespace = testNamespace

		foreign := &corev1.Service{
			ObjectMeta: metav1.ObjectMeta{Name: conflictEndpoint, Namespace: namespace},
			Spec: corev1.ServiceSpec{
				Ports:    []corev1.ServicePort{{Port: 8080}},
				Selector: map[string]string{"app": "foreign"},
			},
		}
		Expect(k8sClient.Create(ctx, foreign)).To(Succeed())
		Expect(k8sClient.Get(ctx, namespacedName(foreign.Name, namespace), foreign)).To(Succeed())
		foreignBefore := foreign.DeepCopy()
		routing := newGenerationRecoveryRouting(routingName, workspaceID, conflictEndpoint)
		Expect(k8sClient.Create(ctx, routing)).To(Succeed())
		DeferCleanup(deleteGenerationRecoveryObjects, routingName, workspaceID, conflictEndpoint, updatedEndpoint)

		routingKey := namespacedName(routingName, namespace)
		var failed controllerv1alpha1.DevWorkspaceRouting
		Eventually(func() (controllerv1alpha1.DevWorkspaceRoutingPhase, error) {
			if err := k8sClient.Get(ctx, routingKey, &failed); err != nil {
				return "", err
			}
			return failed.Status.Phase, nil
		}, timeout, interval).Should(Equal(controllerv1alpha1.RoutingFailed))
		Expect(failed.Status.Message).To(ContainSubstring("already in use"))
		Expect(failed.Status.ObservedGeneration).To(Equal(failed.Generation))
		failedGeneration := failed.Generation
		failedUID := failed.UID

		failed.Spec.Endpoints[testMachineName][0].Name = updatedEndpoint
		Expect(k8sClient.Update(ctx, &failed)).To(Succeed())
		Eventually(func() int64 {
			current := &controllerv1alpha1.DevWorkspaceRouting{}
			if err := k8sClient.Get(ctx, routingKey, current); err != nil {
				return failedGeneration
			}
			return current.Generation
		}, timeout, interval).Should(BeNumerically(">", failedGeneration))

		var recovered controllerv1alpha1.DevWorkspaceRouting
		Eventually(func() (controllerv1alpha1.DevWorkspaceRoutingPhase, error) {
			if err := k8sClient.Get(ctx, routingKey, &recovered); err != nil {
				return "", err
			}
			if recovered.Status.ObservedGeneration != recovered.Generation {
				return "", nil
			}
			return recovered.Status.Phase, nil
		}, timeout, interval).Should(Equal(controllerv1alpha1.RoutingReady))
		Expect(recovered.UID).To(Equal(failedUID))
		Expect(recovered.Generation).To(BeNumerically(">", failedGeneration))
		Expect(recovered.Status.ObservedGeneration).To(Equal(recovered.Generation))

		recoveredService := &corev1.Service{}
		Expect(k8sClient.Get(ctx, namespacedName(updatedEndpoint, namespace), recoveredService)).To(Succeed())
		foreignAfter := &corev1.Service{}
		Expect(k8sClient.Get(ctx, namespacedName(conflictEndpoint, namespace), foreignAfter)).To(Succeed())
		Expect(reflect.DeepEqual(foreignAfter, foreignBefore)).To(BeTrue(), "the foreign Service must remain unchanged")
	})

	It("keeps a current-generation failure terminal after its conflicting Service is removed", func() {
		const routingName = "generation-terminal-routing"
		const workspaceID = "generation-terminal"
		const conflictEndpoint = "terminal-conflict"
		const namespace = testNamespace

		foreign := &corev1.Service{
			ObjectMeta: metav1.ObjectMeta{Name: conflictEndpoint, Namespace: namespace},
			Spec: corev1.ServiceSpec{
				Ports:    []corev1.ServicePort{{Port: 8080}},
				Selector: map[string]string{"app": "foreign"},
			},
		}
		Expect(k8sClient.Create(ctx, foreign)).To(Succeed())
		routing := newGenerationRecoveryRouting(routingName, workspaceID, conflictEndpoint)
		Expect(k8sClient.Create(ctx, routing)).To(Succeed())
		DeferCleanup(deleteGenerationRecoveryObjects, routingName, workspaceID, conflictEndpoint, "")

		routingKey := namespacedName(routingName, namespace)
		var failed controllerv1alpha1.DevWorkspaceRouting
		Eventually(func() (controllerv1alpha1.DevWorkspaceRoutingPhase, error) {
			if err := k8sClient.Get(ctx, routingKey, &failed); err != nil {
				return "", err
			}
			return failed.Status.Phase, nil
		}, timeout, interval).Should(Equal(controllerv1alpha1.RoutingFailed))
		Expect(failed.Status.ObservedGeneration).To(Equal(failed.Generation))
		failureMessage := failed.Status.Message

		Expect(k8sClient.Delete(ctx, foreign)).To(Succeed())
		failed.Annotations = map[string]string{"test.devfile.io/reconcile": "again"}
		Expect(k8sClient.Update(ctx, &failed)).To(Succeed())
		Consistently(func() (controllerv1alpha1.DevWorkspaceRoutingPhase, error) {
			current := &controllerv1alpha1.DevWorkspaceRouting{}
			if err := k8sClient.Get(ctx, routingKey, current); err != nil {
				return "", err
			}
			Expect(current.Generation).To(Equal(failed.Generation))
			Expect(current.Status.ObservedGeneration).To(Equal(current.Generation))
			Expect(current.Status.Message).To(Equal(failureMessage))
			return current.Status.Phase, nil
		}, 2*interval, interval).Should(Equal(controllerv1alpha1.RoutingFailed))
	})
})

// Generated by Codex
func newGenerationRecoveryRouting(name, workspaceID, endpointName string) *controllerv1alpha1.DevWorkspaceRouting {
	attributes := controllerv1alpha1.Attributes{}.PutBoolean(string(controllerv1alpha1.DiscoverableAttribute), true)
	return &controllerv1alpha1.DevWorkspaceRouting{
		ObjectMeta: metav1.ObjectMeta{Name: name, Namespace: testNamespace},
		Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{
			DevWorkspaceId: workspaceID,
			RoutingClass:   controllerv1alpha1.DevWorkspaceRoutingCluster,
			PodSelector:    map[string]string{constants.DevWorkspaceIDLabel: workspaceID},
			Endpoints: map[string]controllerv1alpha1.EndpointList{
				testMachineName: {{
					Name:       endpointName,
					TargetPort: 8080,
					Exposure:   controllerv1alpha1.InternalEndpointExposure,
					Attributes: attributes,
				}},
			},
		},
	}
}

