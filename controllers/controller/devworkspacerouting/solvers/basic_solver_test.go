func TestBasicSolverGetSpecObjectsKubernetes(t *testing.T) {
	solver, meta := newBasicSolverTest(t, nil)
	api := testEndpoint("my--api", 8080, controllerv1alpha1.PublicEndpointExposure, true, "http")
	api.Annotations = map[string]string{"example.com/test": "api"}
	database := testEndpoint("database", 5432, controllerv1alpha1.InternalEndpointExposure, true, "tcp")
	httpEndpoint := testEndpoint("http", 3000, controllerv1alpha1.PublicEndpointExposure, false, "http")
	hidden := testEndpoint("hidden", 9000, controllerv1alpha1.NoneEndpointExposure, true, "http")
	routing := routingForEndpoints(map[string]controllerv1alpha1.EndpointList{"main": {api, database, httpEndpoint, hidden}})

	objects, err := solver.GetSpecObjects(context.Background(), routing, meta)
	if err != nil {
		t.Fatal(err)
	}
	if len(objects.Services) != 3 || len(objects.Ingresses) != 2 || len(objects.Routes) != 0 || objects.PodAdditions != nil {
		t.Fatalf("unexpected routing objects: %d Services, %d Ingresses, %d Routes, PodAdditions=%v", len(objects.Services), len(objects.Ingresses), len(objects.Routes), objects.PodAdditions)
	}

	selector := map[string]string{"workspace": "workspace-id", "component": "devworkspace"}
	serviceLabels := map[string]string{constants.DevWorkspaceIDLabel: "workspace-id"}
	expectedPorts := []corev1.ServicePort{
		{Name: "my-api", Protocol: corev1.ProtocolTCP, Port: 8080, TargetPort: intstr.FromInt(8080)},
		{Name: "database", Protocol: corev1.ProtocolTCP, Port: 5432, TargetPort: intstr.FromInt(5432)},
		{Name: "http", Protocol: corev1.ProtocolTCP, Port: 3000, TargetPort: intstr.FromInt(3000)},
	}
	aggregate := objects.Services[0]
	if aggregate.Name != "workspace-id-service" || aggregate.Namespace != "workspace-namespace" ||
		!reflect.DeepEqual(aggregate.Labels, serviceLabels) || aggregate.Annotations != nil ||
		!reflect.DeepEqual(aggregate.Spec, corev1.ServiceSpec{Type: corev1.ServiceTypeClusterIP, Selector: selector, Ports: expectedPorts}) {
		t.Fatalf("unexpected aggregate Service: %#v", aggregate)
	}

	discoverable := map[string]corev1.Service{}
	for _, service := range objects.Services[1:] {
		discoverable[service.Name] = service
	}
	if len(discoverable) != 2 {
		t.Fatalf("discoverable Services = %v, want my-api and database", discoverable)
	}
	for _, expected := range []struct {
		name string
		port int32
	}{{"my-api", 8080}, {"database", 5432}} {
		service, ok := discoverable[expected.name]
		wantLabels := map[string]string{constants.DevWorkspaceIDLabel: "workspace-id", constants.DevWorkspaceNameLabel: "workspace"}
		wantAnnotations := map[string]string{constants.DevWorkspaceDiscoverableServiceAnnotation: "true"}
		wantPort := []corev1.ServicePort{{Name: expected.name, Protocol: corev1.ProtocolTCP, Port: expected.port, TargetPort: intstr.FromInt(int(expected.port))}}
		if !ok || service.Name != expected.name || service.Namespace != "workspace-namespace" || !reflect.DeepEqual(service.Labels, wantLabels) ||
			!reflect.DeepEqual(service.Annotations, wantAnnotations) ||
			!reflect.DeepEqual(service.Spec, corev1.ServiceSpec{Type: corev1.ServiceTypeClusterIP, Selector: selector, Ports: wantPort}) {
			t.Errorf("unexpected discoverable Service %q: %#v", expected.name, service)
		}
	}

	ingresses := map[string]networkingv1.Ingress{}
	for _, ingress := range objects.Ingresses {
		ingresses[ingress.Name] = ingress
	}
	for _, expected := range []struct {
		name, endpoint, host string
		port                 int32
		annotations          map[string]string
	}{{"workspace-id-my-api", "my--api", "workspace-id-my-api-8080.example.test", 8080, map[string]string{"example.com/test": "api"}},
		{"workspace-id-http", "http", "workspace-id-http-3000.example.test", 3000, nil}} {
		ingress, ok := ingresses[expected.name]
		wantAnnotations := map[string]string{
			"nginx.ingress.kubernetes.io/rewrite-target": "/",
			"nginx.ingress.kubernetes.io/ssl-redirect":   "false",
			constants.DevWorkspaceEndpointNameAnnotation: expected.endpoint,
		}
		for key, value := range expected.annotations {
			wantAnnotations[key] = value
		}
		if !ok || ingress.Namespace != "workspace-namespace" ||
			!reflect.DeepEqual(ingress.Labels, serviceLabels) || !reflect.DeepEqual(ingress.Annotations, wantAnnotations) ||
			ingress.Spec.IngressClassName == nil || *ingress.Spec.IngressClassName != "nginx" || len(ingress.Spec.Rules) != 1 {
			t.Errorf("unexpected Ingress %q metadata/spec: %#v", expected.name, ingress)
			continue
		}
		rule := ingress.Spec.Rules[0]
		if rule.Host != expected.host || rule.HTTP == nil || len(rule.HTTP.Paths) != 1 {
			t.Errorf("unexpected Ingress rule for %q: %#v", expected.name, rule)
			continue
		}
		path := rule.HTTP.Paths[0]
		if path.Path != "/" || path.PathType == nil || *path.PathType != networkingv1.PathTypeImplementationSpecific ||
			path.Backend.Service == nil || path.Backend.Service.Name != "workspace-id-service" || path.Backend.Service.Port.Number != expected.port {
			t.Errorf("unexpected Ingress path for %q: %#v", expected.name, path)
		}
	}

	exposed, ready, err := solver.GetExposedEndpoints(routing.Spec.Endpoints, objects)
	if err != nil || !ready {
		t.Fatalf("GetExposedEndpoints() = (%v, %t, %v), want ready without error", exposed, ready, err)
	}
	wantExposed := controllerv1alpha1.ExposedEndpointList{
		{Name: "my--api", Url: "http://workspace-id-my-api-8080.example.test", Attributes: api.Attributes},
		{Name: "http", Url: "http://workspace-id-http-3000.example.test", Attributes: httpEndpoint.Attributes},
	}
	if !reflect.DeepEqual(exposed["main"], wantExposed) || len(exposed) != 1 {
		t.Fatalf("exposed endpoints = %#v, want only public endpoint URLs", exposed)
	}
}

