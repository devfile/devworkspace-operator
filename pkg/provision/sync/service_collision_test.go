func TestGenericServiceCollisionRejectsForeignOwnership(t *testing.T) {
	for _, scenario := range []string{"no existing refs", "no desired refs", "mismatched UID", "mismatched name", "mismatched kind", "empty desired UID", "missing second ref", "unexpected controller", "matching label with unexpected controller"} {
		t.Run(scenario, func(t *testing.T) {
			desired, existing := collisionServices()
			switch scenario {
			case "no existing refs":
				existing.OwnerReferences = nil
			case "no desired refs":
				desired.OwnerReferences = nil
			case "mismatched UID":
				existing.OwnerReferences[0].UID = "foreign"
			case "mismatched name":
				existing.OwnerReferences[0].Name = "foreign"
			case "mismatched kind":
				existing.OwnerReferences[0].Kind = "Deployment"
			case "empty desired UID":
				desired.OwnerReferences[0].UID = ""
				existing.OwnerReferences[0].UID = ""
			case "missing second ref":
				desired.OwnerReferences = append(desired.OwnerReferences, metav1.OwnerReference{Kind: "Deployment", Name: "async", UID: "async-uid"})
			case "unexpected controller", "matching label with unexpected controller":
				existing.OwnerReferences = append(existing.OwnerReferences, metav1.OwnerReference{Kind: "Deployment", Name: "foreign", UID: "foreign-uid", Controller: ptr.To(true)})
			}
			if scenario == "matching label with unexpected controller" {
				existing.Labels = desired.Labels
			}
			backing := fake.NewClientBuilder().WithObjects(existing).Build()
			// A stale filtered cache may miss even a Service whose label now matches.
			stale := interceptor.NewClient(backing, interceptor.Funcs{Get: func(_ context.Context, _ client.WithWatch, key client.ObjectKey, _ client.Object, _ ...client.GetOption) error {
				return apierrors.NewNotFound(schema.GroupResource{Resource: "services"}, key.Name)
			}})
			cached := &countingServiceClient{Client: stale}
			fresh := &countingServiceClient{Client: backing}
			_, err := SyncObjectWithCluster(desired, ClusterAPI{Client: cached, NonCachingClient: fresh, Ctx: context.Background(), Logger: logr.Discard()})
			var conflict *UnrecoverableSyncError
			if !errors.As(err, &conflict) || !strings.Contains(err.Error(), desired.Name) || !strings.Contains(err.Error(), "Service") {
				t.Fatalf("want permanent Service-name conflict, got %v", err)
			}
			if cached.creates != 1 || fresh.gets != 1 || cached.updates != 0 || cached.deletes != 0 || fresh.creates != 0 || fresh.updates != 0 || fresh.deletes != 0 {
				t.Fatalf("foreign collision made unexpected calls: cached=%+v fresh=%+v", cached, fresh)
			}
			actual := &corev1.Service{}
			if err := backing.Get(context.Background(), client.ObjectKeyFromObject(existing), actual); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(actual, existing) {
				t.Fatalf("foreign Service changed: %#v", actual)
			}
		})
	}
}

