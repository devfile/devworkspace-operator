func newBasicSolverTest(t *testing.T, getErr error, objects ...client.Object) (*BasicSolver, DevWorkspaceMetadata) {
	t.Helper()
	previousConfig := config.GetGlobalConfig()
	config.SetGlobalConfigForTesting(&controllerv1alpha1.OperatorConfiguration{Routing: &controllerv1alpha1.RoutingConfig{ClusterHostSuffix: "example.test"}})
	t.Cleanup(func() { config.SetGlobalConfigForTesting(previousConfig) })
	infrastructure.InitializeForTesting(infrastructure.Kubernetes)
	scheme := runtime.NewScheme()
	if err := corev1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	cl := fake.NewClientBuilder().WithScheme(scheme).WithObjects(objects...).Build()
	var solverClient client.Client = cl
	if getErr != nil {
		solverClient = &failingServiceGetClient{Client: cl, err: getErr}
	}
	solver, err := (&SolverGetter{}).GetSolver(solverClient, controllerv1alpha1.DevWorkspaceRoutingBasic)
	if err != nil {
		t.Fatal(err)
	}
	basicSolver, ok := solver.(*BasicSolver)
	if !ok {
		t.Fatalf("GetSolver returned %T, want *BasicSolver", solver)
	}
	return basicSolver, DevWorkspaceMetadata{
		DevWorkspaceId:   "workspace-id",
		DevWorkspaceName: "workspace",
		Namespace:        "workspace-namespace",
		PodSelector:      map[string]string{"workspace": "workspace-id", "component": "devworkspace"},
	}
}

