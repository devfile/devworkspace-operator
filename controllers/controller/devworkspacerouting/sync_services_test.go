func TestSyncServicesDeletesOwnedService(t *testing.T) {
	scheme := runtime.NewScheme()
	if err := corev1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	owned := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "unused", Namespace: "ns", UID: "owned-service", Labels: map[string]string{constants.DevWorkspaceIDLabel: "mine"}, OwnerReferences: []metav1.OwnerReference{{Kind: "DevWorkspaceRouting", UID: "mine-routing", Controller: ptr.To(true)}}}}
	cl := fake.NewClientBuilder().WithScheme(scheme).WithObjects(owned).Build()
	r := DevWorkspaceRoutingReconciler{Client: cl, Scheme: scheme, Log: logr.Discard()}
	routing := &controllerv1alpha1.DevWorkspaceRouting{ObjectMeta: metav1.ObjectMeta{Name: "routing-mine", Namespace: "ns", UID: "mine-routing"}, Spec: controllerv1alpha1.DevWorkspaceRoutingSpec{DevWorkspaceId: "mine"}}
	ready, _, err := r.syncServices(routing, nil)
	if err != nil || ready {
		t.Fatalf("want pending deletion, got ready=%v err=%v", ready, err)
	}
	if err := cl.Get(context.Background(), client.ObjectKeyFromObject(owned), &corev1.Service{}); !apierrors.IsNotFound(err) {
		t.Fatalf("owned Service still exists: %v", err)
	}
}

