func TestSyncDiscoverableServiceUpdatesOwnedService(t *testing.T) {
	scheme := runtime.NewScheme()
	if err := corev1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	existing := &corev1.Service{ObjectMeta: metav1.ObjectMeta{Name: "api", Namespace: "ns", UID: "owned-service", Labels: map[string]string{constants.DevWorkspaceIDLabel: "mine"}, OwnerReferences: []metav1.OwnerReference{{Kind: "DevWorkspaceRouting", UID: "mine-routing", Controller: ptr.To(true)}}}, Spec: corev1.ServiceSpec{ClusterIP: "10.0.0.1", Selector: map[string]string{"app": "old"}}}
	desired := existing.DeepCopy()
	desired.Annotations = map[string]string{constants.DevWorkspaceDiscoverableServiceAnnotation: "true"}
	desired.Spec.ClusterIP = ""
	desired.Spec.Selector = map[string]string{"app": "mine"}
	cl := fake.NewClientBuilder().WithScheme(scheme).WithObjects(existing).Build()
	_, err := SyncObjectWithCluster(desired, ClusterAPI{Client: cl, NonCachingClient: cl, Ctx: context.Background(), Logger: logr.Discard()})
	var pending *NotInSyncError
	if !errors.As(err, &pending) {
		t.Fatalf("want pending update, got %v", err)
	}
	actual := &corev1.Service{}
	if err := cl.Get(context.Background(), client.ObjectKeyFromObject(existing), actual); err != nil {
		t.Fatal(err)
	}
	if actual.Spec.Selector["app"] != "mine" || actual.Spec.ClusterIP != "10.0.0.1" || actual.UID != "owned-service" {
		t.Fatalf("owned Service was not updated in place: %#v", actual)
	}
}

