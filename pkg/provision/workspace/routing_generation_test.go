func TestSyncRoutingToClusterFailedGenerationBehavior(t *testing.T) {
	scheme := runtime.NewScheme()
	if err := dw.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	if err := controllerv1alpha1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}

	workspace := &common.DevWorkspaceWithConfig{
		DevWorkspace: &dw.DevWorkspace{
			ObjectMeta: metav1.ObjectMeta{Name: "workspace", Namespace: "test", UID: types.UID("workspace-uid")},
			Spec:       dw.DevWorkspaceSpec{RoutingClass: "cluster"},
			Status:     dw.DevWorkspaceStatus{DevWorkspaceId: "workspace-id"},
		},
		Config: config.GetConfigForTesting(&controllerv1alpha1.OperatorConfiguration{}),
	}
	desiredRouting, err := getSpecRouting(workspace, scheme)
	if err != nil {
		t.Fatal(err)
	}

	const message = "endpoint name is already in use"
	for _, tc := range []struct {
		name               string
		observedGeneration int64
		wantRetry          bool
	}{
		{name: "stale failure retries", observedGeneration: 3, wantRetry: true},
		{name: "current failure stays terminal", observedGeneration: 4},
		{name: "legacy failure stays terminal", observedGeneration: 0},
	} {
		t.Run(tc.name, func(t *testing.T) {
			routing := desiredRouting.DeepCopy()
			routing.Generation = 4
			routing.Status = controllerv1alpha1.DevWorkspaceRoutingStatus{
				Phase:              controllerv1alpha1.RoutingFailed,
				Message:            message,
				ObservedGeneration: tc.observedGeneration,
			}
			cl := fake.NewClientBuilder().WithScheme(scheme).
				WithStatusSubresource(&controllerv1alpha1.DevWorkspaceRouting{}).
				WithObjects(routing).Build()
			api := sync.ClusterAPI{Client: cl, Scheme: scheme, Logger: logr.Discard(), Ctx: context.Background()}

			_, _, statusMessage, err := SyncRoutingToCluster(workspace, api)
			if tc.wantRetry {
				var retryErr *dwerrors.RetryError
				if !errors.As(err, &retryErr) {
					t.Fatalf("want stale failed routing to retry, got %T: %v", err, err)
				}
				if retryErr.RequeueAfter != 5*time.Second {
					t.Errorf("retry delay = %s, want 5s", retryErr.RequeueAfter)
				}
				if retryErr.Message != message {
					t.Errorf("retry message = %q, want %q", retryErr.Message, message)
				}
			} else {
				var failErr *dwerrors.FailError
				if !errors.As(err, &failErr) {
					t.Fatalf("want terminal failure, got %T: %v", err, err)
				}
				if failErr.Message != message {
					t.Errorf("failure message = %q, want %q", failErr.Message, message)
				}
			}
			if statusMessage != message {
				t.Errorf("status message = %q, want %q", statusMessage, message)
			}
		})
	}
}
